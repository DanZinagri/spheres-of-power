def mark_generators(body: Tag, soup_factory) -> None:
    """The wiki's random-table generators were embedded HTML widgets (iframes, not mirrored).
    Each becomes a .sop-roller marker; Quartz's SopRoller script rolls on the table after it."""
    for iframe in body.select("iframe.html-block-iframe"):
        heading = iframe.find_previous(re.compile(r"^h[1-6]$"))
        if heading is None or "generator" not in heading.get_text(" ", strip=True).lower():
            continue
        marker = soup_factory.new_tag("div", attrs={"class": "sop-roller"})
        holder = iframe.parent
        if holder is not None and holder.name == "p" and not holder.get_text(strip=True):
            holder.replace_with(marker)
        else:
            iframe.replace_with(marker)


def drop_book_navboxes(body: Tag) -> None:
    """Remove the per-book navigation boxes ("Spheres of Power by Drop Dead Studios" + class /
    sphere / product links) repeated at the bottom of most pages; the home page lists it all."""
    for table in body.find_all("table"):
        if table.parent is None or not is_layout_table(table):
            continue
        first = next((c.get_text(" ", strip=True) for c in table.find_all(["td", "th"])
                      if c.get_text(strip=True)), "")
        if re.fullmatch(r".{3,80}\sby\s.{3,80}", first) and len(table.find_all("a")) >= 5:
            table.decompose()


def drop_class_option_archetypes(body: Tag) -> None:
    """Sphere pages' "<Sphere> Sphere Class Options" sections: drop their "Archetypes" part (the
    class pages list archetypes already), and the whole section if nothing else is left."""
    is_heading = lambda el: isinstance(el, Tag) and re.fullmatch(r"h[1-6]", el.name or "")
    level = lambda el: int(el.name[1])
    for h in body.find_all(re.compile(r"^h[1-6]$")):
        if h.parent is None or not re.search(r"(?i)sphere class options\s*$", h.get_text(" ", strip=True)):
            continue
        sib = h.find_next_sibling()
        while sib is not None and not (is_heading(sib) and level(sib) <= level(h)) and sib.name != "hr":
            nxt = sib.find_next_sibling()
            if is_heading(sib) and re.fullmatch(r"(?i)\s*archetypes\s*", sib.get_text(" ", strip=True)):
                sub = sib.find_next_sibling()
                while sub is not None and not (is_heading(sub) and level(sub) <= level(sib)) \
                        and sub.name != "hr":
                    after = sub.find_next_sibling()
                    sub.decompose()
                    sub = after
                sib.decompose()
                nxt = sub
            sib = nxt
        rest = h.find_next_sibling()
        if rest is None or rest.name == "hr" or (is_heading(rest) and level(rest) <= level(h)):
            h.decompose()


def drop_sections(body: Tag, pattern: re.Pattern) -> None:
    """Remove each heading matching pattern together with its section."""
    is_heading = lambda el: isinstance(el, Tag) and re.fullmatch(r"h[1-6]", el.name or "")
    for h in body.find_all(re.compile(r"^h[1-6]$")):
        if h.parent is None or not pattern.match(h.get_text(" ", strip=True)):
            continue
        level = int(h.name[1])
        sib = h.find_next_sibling()
        while sib is not None and not (is_heading(sib) and int(sib.name[1]) <= level)                 and sib.name != "hr":
            nxt = sib.find_next_sibling()
            sib.decompose()
            sib = nxt
        h.decompose()


def preprocess(body: Tag, soup_factory, excluded: set[str] | None = None,
               nav: bool = False) -> None:
    """Rewrite wikidot widgets into plain HTML that markdownify understands."""
    group_columns(body, soup_factory)
    mark_generators(body, soup_factory)
    for sel in ["#toc", "script", "style", ".wd-adunit", "iframe", ".page-tags",
                ".footnotes-footer .title", ".printuser"]:
        for el in body.select(sel):
            el.decompose()

    # Tabviews (e.g. Ultimate / Original): .sop-tabs > .sop-tab (label + content). Quartz turns
    # these into clickable tabs (components/SopTabs.tsx); Obsidian shows each label then its content.
    for tabview in body.select(".yui-navset"):
        labels = [li.get_text(" ", strip=True) for li in tabview.select(".yui-nav li")]
        panes = tabview.select(".yui-content > div")
        wrapper = soup_factory.new_tag("div", attrs={"class": "sop-tabs"})
        for label, pane in zip(labels, panes):
            # data-tab lets CSS/JS/Pagefind target a tab by name (pagefind.yml skips "original")
            tab_id = re.sub(r"[^a-z0-9]+", "-", label.lower()).strip("-") or "tab"
            tab = soup_factory.new_tag("div", attrs={"class": "sop-tab", "data-tab": tab_id})
            name = soup_factory.new_tag("div", attrs={"class": "sop-tab-label"})
            name.string = label
            tab.append(name)
            tab.append(pane)
            wrapper.append(tab)
        tabview.replace_with(wrapper)

    # Collapsibles: drop the "show/hide" toggles, keep the unfolded content with its label.
    for block in body.select(".collapsible-block"):
        link = block.select_one(".collapsible-block-folded a")
        label = link.get_text(" ", strip=True) if link else ""
        label = re.sub(r"^[+\-]\s*", "", label)
        content = block.select_one(".collapsible-block-content")
        wrapper = soup_factory.new_tag("div")
        if label and not re.match(r"(?i)^(show|hide)\b", label):
            p = soup_factory.new_tag("p")
            b = soup_factory.new_tag("strong")
            b.string = label
            p.append(b)
            wrapper.append(p)
        if content:
            wrapper.append(content)
        block.replace_with(wrapper)

    # Footnote refs: <sup class="footnoteref"><a>1</a></sup> -> [^1]
    for sup in body.select("sup.footnoteref"):
        sup.replace_with(NavigableString(f"[^{sup.get_text(strip=True)}]"))
    footer = body.select_one(".footnotes-footer")
    if footer:
        lines = []
        for fn in footer.select(".footnote-footer"):
            a = fn.find("a")
            num = a.get_text(strip=True) if a else str(len(lines) + 1)
            if a:
                a.decompose()
            lines.append(f"[^{num}]: {fn.get_text(' ', strip=True).lstrip('. ')}")
        footer.replace_with(NavigableString("\n\n" + "\n".join(lines) + "\n\n" if lines else ""))

    # Wikidot's colored spans / "redtext" etc. are just styling; unwrap.
    for span in body.find_all("span"):
        span.unwrap()
    body.smooth()  # merge text split by the unwrapped spans
    if not nav:
        drop_book_navboxes(body)
        drop_sections(body, DROPPED_SECTIONS)
        drop_class_option_archetypes(body)
    prune_tagged_entries(body, nav)
    if excluded:
        prune_excluded_entries(body, excluded)
        if nav:
            prune_excluded(body, excluded)
    archetype_section_tables(body, soup_factory)

    # Store boxes: cover image linking to a shop + <strong>Book</strong> + price -> "Source: [Book](shop)".
    for img in body.find_all("img"):
        a = img.parent if img.parent and img.parent.name == "a" else None
        if not a or not a.get("href", "").startswith("http"):
            continue
        box = a.parent
        name = a.find_next_sibling("strong")
        if box and box.parent and name and "$" in box.get_text():
            p = soup_factory.new_tag("p")
            em = soup_factory.new_tag("em")
            em.append("Source: ")
            link = soup_factory.new_tag("a", href=a["href"])
            link.string = name.get_text(" ", strip=True)
            em.append(link)
            p.append(em)
            box.replace_with(p)

    # Tables: real data tables stay markdown tables; layout tables and navboxes get flattened.
    for table in reversed(body.find_all("table")):
        if table.parent is None:
            continue
        if table.get("data-layout") or is_layout_table(table):
            flatten_table(table, soup_factory)


def is_layout_table(table: Tag) -> bool:
    if "wiki-content-table" not in (table.get("class") or []):
        return True
    rows = table.find_all("tr", recursive=False) or table.select(":scope > tbody > tr")
    widths = [sum(int(c.get("colspan", 1) or 1) for c in r.find_all(["td", "th"], recursive=False))
              for r in rows]
    if not widths or max(widths) < 3:
        return False
    # Navbox: some rows are one cell spanning the table, and the content is basically all links.
    spanning = sum(1 for r in rows if len(r.find_all(["td", "th"], recursive=False)) == 1)
    text = table.get_text(" ", strip=True)
    link_text = " ".join(a.get_text(" ", strip=True) for a in table.find_all("a"))
    return spanning >= 2 and len(link_text) > 0.6 * max(len(text), 1)


def flatten_table(table: Tag, soup_factory) -> None:
    out = soup_factory.new_tag("div")
    rows = table.find_all("tr")
    for tr in rows:
        if tr.find_parent("table") is not table:
            continue
        cells = [c for c in tr.find_all(["td", "th"], recursive=False) if c.get_text(strip=True) or c.find("img")]
        if not cells:
            continue
        if len(cells) == 1:
            cell = cells[0]
            # a lone short cell with no links in a navbox is a section label
            if len(rows) > 1 and not cell.find(["a", "p", "ul", "table"]) and len(cell.get_text(strip=True)) < 60:
                p = soup_factory.new_tag("p")
                b = soup_factory.new_tag("strong")
                b.string = cell.get_text(" ", strip=True)
                p.append(b)
                out.append(p)
            else:
                div = soup_factory.new_tag("div")
                for child in list(cell.contents):
                    div.append(child)
                out.append(div)
        else:
            p = soup_factory.new_tag("p")
            for i, cell in enumerate(cells):
                if i:
                    p.append(" · ")
                for child in list(cell.contents):
                    p.append(child)
            out.append(p)
    table.replace_with(out)


def wikidot_tabs(md: str) -> str:
    """Wikidot tab markup some source pages print as text ("[[tab Name]]" ... "[[/tab]]") -> tab sets.
    A stray "[[/tab]]" with no opening tag (the tag lost on the source page) is dropped."""
    if "[[tab " not in md and "[[/tab" not in md:
        return md
    lines, out = md.split("\n"), []
    in_set = in_tab = False

    def next_is_tab(i: int) -> bool:
        nxt = next((l.strip() for l in lines[i + 1:] if l.strip()), "")
        return nxt.startswith("[[tab ")

    for i, l in enumerate(lines):
        s = l.strip()
        if s in ("[[tabview]]", "[[tabs]]"):
            continue
        if s in ("[[/tabview]]", "[[/tabs]]"):
            if in_tab:
                out += ["", "</div>", ""]
                in_tab = False
            if in_set:
                out += ["</div>", ""]
                in_set = False
            continue
        if m := re.fullmatch(r"\[\[tab (.+?)\]\]", s):
            if in_tab:
                out += ["", "</div>", ""]
            if not in_set:
                out += ["", '<div class="sop-tabs">', ""]
                in_set = True
            label = m.group(1).strip()
            tab_id = re.sub(r"[^a-z0-9]+", "-", label.lower()).strip("-")
            out += [f'<div class="sop-tab" data-tab="{tab_id}">', "",
                    f'<div class="sop-tab-label">{html.escape(label)}</div>', ""]
            in_tab = True
            continue
        if s == "[[/tab]]":
            if in_tab:
                out += ["", "</div>", ""]
                in_tab = False
                if in_set and not next_is_tab(i):
                    out += ["</div>", ""]
                    in_set = False
            continue
        out.append(l)
    if in_tab:
        out += ["", "</div>", ""]
    if in_set:
        out += ["</div>", ""]
    return re.sub(r"\n{3,}", "\n\n", "\n".join(out))


def unpad_bold(line: str) -> str:
    """'** text **' -> ' **text** ' for each bold span of a line (markers paired in order)."""
    parts = line.split("**")
    if len(parts) < 3 or len(parts) % 2 == 0:  # no spans, or an unpaired marker: leave it
        return line
    out = parts[0]
    for k in range(1, len(parts), 2):
        inner, after = parts[k], parts[k + 1]
        if not inner.strip():
            out += f"**{inner}**{after}"
            continue
        lead = inner[:len(inner) - len(inner.lstrip(" \t"))]
        trail = inner[len(inner.rstrip(" \t")):]
        out += f"{lead}**{inner.strip(' \t')}**{trail}{after}"
    return out


SMALL_WORDS = {"a", "an", "and", "as", "at", "by", "for", "from", "in", "into", "of", "on", "or", "the",
               "to", "vs", "with"}


def _title_case(text: str) -> str:
    words = text.lower().split(" ")
    return " ".join(w if (i and w in SMALL_WORDS) else w[:1].upper() + w[1:] for i, w in enumerate(words))


def normalize_formatting(md: str) -> str:
    """Site-wide consistency fixes for formatting the source wiki applies unevenly:
    - source credits as one italic line ("*Source: ...*"), not "**Source:** ...";
    - heading text not wrapped whole in bold/italics, no trailing colon, no ALL CAPS;
    - feat labels bold with the colon inside ("**Benefit:**")."""
    md = re.sub(r"^\*\*Source:\*\*[ \t]*(.+?)[ \t]*$", lambda m: f"*Source: {m.group(1).strip('*')}*", md, flags=re.M)

    def heading(m):
        hashes, text = m.group(1), m.group(2).strip()
        while (w := re.fullmatch(r"(\*\*|\*|__|_)(.+)\1", text)) and "*" not in w.group(2).replace("**", ""):
            text = w.group(2).strip()
        text = re.sub(r"[ \t]*:$", "", text)
        letters = re.sub(r"\[[^\]]*\]|\([^)]*\)", "", text)
        if sum(c.isalpha() for c in letters) > 4 and letters.isupper():
            text = re.sub(r"[^\[(]+(?=[\[(]|$)", lambda p: _title_case(p.group(0)), text, count=1)
        return f"{hashes} {text}"
    md = re.sub(r"^(#{1,6}) (.+)$", heading, md, flags=re.M)
    # "-[[Link]]" list items (no space after the dash) render as plain text, not a list
    md = re.sub(r"^-(\[\[)", r"- \1", md, flags=re.M)
    labels = r"Prerequisites?|Benefits?|Normal|Special|Requirements?"
    # "**Combat Training (Ex)**: text" -> "**Combat Training (Ex):** text" (colon inside the bold)
    md = re.sub(r"^(\s*(?:- )?)\*\*([^*\n]+?)\*\*:", r"\1**\2:**", md, flags=re.M)
    md = re.sub(rf"^({labels}):[ \t]*", r"**\1:** ", md, flags=re.M)
    return md


NOT_FEATURES = {"wiki note", "note", "notes", "special", "source", "prerequisite", "prerequisites",
                "benefit", "normal", "example", "author's note", "designer's note"}
PLAIN_FEATURES = r"Proficiencies|Weapon and Armor Proficiency|Casting|Spell Pool|Skills|Class Skills|Alignment"


def feature_headings(lines: list[str]) -> list[str]:
    """'**Combat Training (Ex):** text' (or a plain 'Proficiencies: text') at the start of a
    paragraph -> '## Combat Training (Ex)' followed by the text as its own paragraph."""
    out = []
    for i, l in enumerate(lines):
        starts = i == 0 or not lines[i - 1].strip()
        m = (re.match(r"\*\*([^*\n]+?):\*\*[ \t]*(.*)$", l) or re.match(rf"({PLAIN_FEATURES}):[ \t]+(.*)$", l)
             or re.match(r"\*\*([^*\n]+?)\*\*()[ \t]*$", l))  # a feature name on its own bold line
        if starts and m and m.group(1).strip().lower().replace("’", "'") not in NOT_FEATURES:
            out += [f"## {m.group(1).strip()}", ""]
            if m.group(2).strip():
                out.append(m.group(2))
            continue
        out.append(l)
    return out


