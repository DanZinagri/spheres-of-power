def cut_section(md: str, heading: str) -> tuple[str, str]:
    """Remove the section with this exact heading text; return (rest, its body with the shallowest
    inner heading level normalized to ##). The section ends at a heading of the same or higher
    level or at the end of its block (</div>)."""
    lines = md.split("\n")
    level_of = lambda l: len(m.group(1)) if (m := re.match(r"(#{1,6}) ", l)) else 0
    start = next((i for i, l in enumerate(lines) if level_of(l) and l.lstrip("#").strip() == heading), None)
    if start is None:
        return md, ""
    level = level_of(lines[start])
    end = next((i for i in range(start + 1, len(lines))
                if 0 < level_of(lines[i]) <= level or lines[i].strip() == "</div>"), len(lines))
    chunk = lines[start + 1:end]
    if "\n".join(chunk).count("<div") != "\n".join(chunk).count("</div>"):
        return md, ""
    inner = min((level_of(l) for l in chunk if level_of(l)), default=level + 1)
    body = [("#" * max(2, level_of(l) - inner + 2) + " " + l.lstrip("#").lstrip()) if level_of(l) else l
            for l in chunk]
    return "\n".join(lines[:start] + lines[end:]), "\n".join(body).strip()


def split_drawbacks(md: str, overview: str = DRAWBACKS_HEADING) -> tuple[str, str, list[tuple[str, str]]]:
    """Casting Traditions' "Sphere-Specific Drawbacks" section: one "### [[Sphere]]" group of
    "#### Drawback" entries per sphere. Returns (page markdown with the groups replaced by a link
    to the overview page, the section's intro text, [(sphere note name, that sphere's entries)])."""
    lines = md.split("\n")
    level_of = lambda l: len(m.group(1)) if (m := re.match(r"(#{1,6}) ", l)) else 0
    start = next((i for i, l in enumerate(lines)
                  if level_of(l) and l.lstrip("#").strip() == DRAWBACKS_HEADING), None)
    if start is None:
        return md, "", []
    level = level_of(lines[start])
    end = next((i for i in range(start + 1, len(lines))
                if 0 < level_of(lines[i]) <= level or lines[i].strip() == "</div>"), len(lines))
    section = lines[start + 1:end]
    groups = [i for i, l in enumerate(section) if level_of(l) == level + 1]
    if not groups or "\n".join(section).count("<div") != "\n".join(section).count("</div>"):
        return md, "", []
    intro = "\n".join(section[:groups[0]]).strip()
    spheres = []
    for n, i in enumerate(groups):
        m = re.search(r"\[\[([^\]|#]+)", section[i])
        name = m.group(1) if m else section[i].lstrip("#").strip()
        chunk = section[i + 1:groups[n + 1] if n + 1 < len(groups) else len(section)]
        inner = min((level_of(l) for l in chunk if level_of(l)), default=level + 2)
        body = [("#" * max(2, level_of(l) - inner + 2) + " " + l.lstrip("#").lstrip()) if level_of(l) else l
                for l in chunk]
        if any(level_of(l) for l in body):  # skip groups left empty (e.g. "Universal" after SM—)
            spheres.append((name, "\n".join(body).strip()))
    keep = [lines[start], "", intro, "",
            f"*Each sphere's drawbacks are on their own page: see [[{overview}]].*", ""]
    return "\n".join(lines[:start] + keep + lines[end:]), intro, spheres


def add_feats_links(home_md: str, feats: dict[str, str], drawbacks: dict[str, str] | None = None) -> str:
    """Home page Magic Spheres list: "[[Alteration]]" -> "[[Alteration]] | [[Alteration Sphere Feats|Feats]]"."""
    out, inside = [], False
    for line in home_md.split("\n"):
        if line.strip().startswith(("**Magic Spheres**", "**Skill Spheres**", "**Combat Spheres**")):
            inside = True
        elif inside and (re.fullmatch(r"\*\*[^*]+\*\*", line.strip()) or line.strip() in ("---", "</div>")):
            inside = False
        if inside:
            # "[[Alchemy]]" or "[[Warleader (warleader-sphere)|Warleader]]"
            m = re.match(r"\[\[([^\]|#]+)(?:\|[^\]]*)?\]\]", line)
            if m:
                extra = ""
                if m.group(1) in feats:
                    extra += f" | [[{feats[m.group(1)]}|Feats]]"
                if drawbacks and m.group(1) in drawbacks:
                    extra += f" | [[{drawbacks[m.group(1)]}|Drawbacks]]"
                line = m.group(0) + extra + line[m.end():]
        out.append(line)
    return "\n".join(out)


def set_column_counts(md: str) -> str:
    """Tag each .sop-columns grid with --cols: the number of side-by-side columns it holds.

    Columns containing a markdown table span the full row (see custom.scss), so they don't count;
    the CSS uses --cols to avoid creating empty tracks on wide screens."""
    lines = md.split("\n")
    stack: list[list] = []  # ["grid", line_idx, narrow, total] / ["col", has_table]
    for i, line in enumerate(lines):
        s = line.strip()
        if s.startswith('<div class="sop-columns"'):
            stack.append(["grid", i, 0, 0])
        elif s == '<div class="sop-col">':
            stack.append(["col", False])
        elif s.startswith("<div") and not s.endswith("</div>"):
            stack.append(["other"])  # e.g. tabs; one-line tab labels open and close on one line
        elif s.startswith("| ---") and stack:
            col = next((c for c in reversed(stack) if c[0] == "col"), None)
            if col:
                col[1] = True
        elif s == "</div>" and stack:
            top = stack.pop()
            if top[0] == "other":
                continue
            if top[0] == "col":
                grid = next((g for g in reversed(stack) if g[0] == "grid"), None)
                if grid:
                    grid[3] += 1
                    grid[2] += 0 if top[1] else 1
            else:
                n = top[2] or top[3] or 1
                lines[top[1]] = f'<div class="sop-columns" style="--cols: {n}">'
    return "\n".join(lines)


ARCHETYPES_HEADING = re.compile(r"\s*archetypes\s*", re.I)


def archetype_runs(body: Tag) -> list[tuple[Tag, list[tuple[Tag, list[Tag]]]]]:
    """Class pages list archetypes as an 'Archetypes' heading followed by one sub-heading per
    archetype (a link + tags) with a short description paragraph or two. Returns
    (archetypes heading, [(entry heading, description paragraphs)]) for each such section whose
    entries are all that simple; anything more complex is left alone."""
    is_h = lambda el: isinstance(el, Tag) and re.fullmatch(r"h[1-6]", el.name or "")
    runs = []
    for h in body.find_all(re.compile(r"^h[1-6]$")):
        if not ARCHETYPES_HEADING.fullmatch(h.get_text(" ", strip=True)):
            continue
        level = int(h.name[1])
        sib = h.find_next_sibling()
        while sib is not None and not is_h(sib) and sib.name != "hr":  # intro text stays as is
            sib = sib.find_next_sibling()
        entries, simple = [], True
        while sib is not None and is_h(sib) and int(sib.name[1]) > level:
            if not sib.find("a", href=True):
                break
            descs, nxt = [], sib.find_next_sibling()
            while nxt is not None and not is_h(nxt) and nxt.name != "hr":
                descs.append(nxt)
                nxt = nxt.find_next_sibling()
            if len(descs) > 3 or any(d.name != "p" for d in descs):
                simple = False
                break
            entries.append((sib, descs))
            sib = nxt
        if simple and entries:
            runs.append((h, entries))
    return runs


def archetype_section_tables(body: Tag, soup_factory) -> None:
    """Replace simple archetype sections with an Archetype | Description table."""
    for _, entries in archetype_runs(body):
        table = soup_factory.new_tag("table", attrs={"class": "wiki-content-table"})
        header = soup_factory.new_tag("tr")
        for label in ("Archetype", "Description"):
            th = soup_factory.new_tag("th")
            th.string = label
            header.append(th)
        table.append(header)
        for heading, descs in entries:
            row = soup_factory.new_tag("tr")
            name, desc = soup_factory.new_tag("td"), soup_factory.new_tag("td")
            for child in list(heading.contents):
                name.append(child)
            for i, d in enumerate(descs):
                if i:
                    desc.append(soup_factory.new_tag("br"))
                for child in list(d.contents):
                    desc.append(child)
            row.append(name)
            row.append(desc)
            table.append(row)
        entries[0][0].insert_before(table)
        for heading, descs in entries:
            heading.decompose()
            for d in descs:
                d.decompose()


