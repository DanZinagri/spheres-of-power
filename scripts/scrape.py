def archetype_tables(md: str) -> str:
    """Runs of '**Class** ([[A]], [[B]] ...)' lines -> a Class | Archetypes | Class Options table.

    On the wiki each class line can be followed by '| [[Alternate Class Features]]'-style lines
    (wikidot's pipe separator); those become the Class Options column."""
    out: list[str] = []
    run: list[dict] = []
    held_blank = 0

    def cell(text: str) -> str:
        text = " ".join(text.split())
        text = re.sub(r"(\s*,\s*){2,}", ", ", text).strip(" ,")
        return re.sub(r"(?<!\\)\|", r"\\|", text)

    def flush():
        if len(run) >= 3:
            options = any(r["extras"] for r in run)
            head = "| Class | Archetypes |" + (" Class Options |" if options else "")
            rows = [head, "| --- | --- |" + (" --- |" if options else "")]
            for r in run:
                if "[[" not in r["arch"] and not r["extras"]:
                    continue  # every archetype was in an excluded book
                row = f"| **{aon_class_link(r['cls'].strip())}** | {cell(r['arch'])} |"
                if options:
                    row += " " + " · ".join(cell(e) for e in r["extras"]) + " |"
                rows.append(row)
            out.extend(["", *rows, ""])
        else:
            for r in run:
                out.extend(r["lines"])
        run.clear()

    for line in md.split("\n"):
        stripped = line.strip()
        m = ARCHETYPE_LINE.match(stripped)
        if m:
            run.append({"lines": [line], "cls": m.group(1), "arch": m.group(2), "extras": []})
            held_blank = 0
        elif run and not held_blank and (stripped.startswith("|") or re.fullmatch(r"(\[\[[^\]]+\]\]\s*)+", stripped)):
            # continuation of the previous class: "| [[Alchemist Discoveries]]" (the wiki sometimes
            # drops the "|", e.g. "[[Sorcerer Bloodlines]]")
            run[-1]["lines"].append(line)
            extra = stripped.lstrip("| ").strip()
            if extra:
                run[-1]["extras"].append(extra)
        elif not stripped and run:
            held_blank += 1  # blank lines between class lines don't end the run
        else:
            flush()
            out.extend([""] * held_blank)
            held_blank = 0
            out.append(line)
    flush()
    return re.sub(r"\n{3,}", "\n\n", "\n".join(out))


