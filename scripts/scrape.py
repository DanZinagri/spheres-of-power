def aon_class_link(name: str) -> str:
    """'Barbarian, Unchained' -> '[Barbarian, Unchained](...ItemName=Barbarian%20(Unchained))'."""
    key = AON_CLASS_ALIASES.get(name, re.sub(r"^(.+), Unchained$", r"\1 (Unchained)", name))
