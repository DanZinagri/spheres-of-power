        if not f:
            print(f"warning: rewrite: no page {stem!r}")
            continue
        text = f.read_text(encoding="utf-8")
        head, body = text.split(GENERATED_MARK, 1)
        new = body
        for pattern, repl in edits:
            new, n = re.subn(pattern, lambda m: m.expand(repl), new, flags=re.M)
