def sphere_lists(md: str) -> str:
    """Inside the home page's Spheres block, each category's sphere lines ("[[Alteration]] |
    [[...|Feats]] | [[...|Drawbacks]]") become one tight list with " · " separators."""
    out, inside, pending_blank = [], False, False
    for line in md.split("\n"):
        s = line.strip()
        if s.startswith('<div class="sop-spheres'):  # also the Feat Types block
            inside = True
        elif inside and s == "</div>":
            inside = False
        if inside and s.startswith("[["):
            out.append("- " + re.sub(r"\]\]\s*\|\s*\[\[", "]] · [[", s))
            pending_blank = False
            continue
        if inside and not s and out and out[-1].startswith("- "):
            pending_blank = True  # blank line inside a category's list: keep the list together
            continue
        if pending_blank:
            out.append("")
            pending_blank = False
        out.append(line)
    return "\n".join(out)


def class_archetype_cells(md: str) -> list[str]:
    """The Archetype cells (link + tags) of a class page's first "Archetype | Description" table."""
    cells, inside = [], False
    for line in md.split("\n"):
        if line.startswith("| Archetype | Description |"):
            inside = True
            continue
        if inside:
            if not line.startswith("|"):
                break
            if line.startswith("| ---"):
                continue
            m = re.match(r"\|\s*(.*?)\s*\|(?!\|)", line.replace("\\|", "\x00"))
            if m and m.group(1):
                cells.append(m.group(1).replace("\x00", "\\|"))
    if not cells:
        # no table (e.g. Agent): link headings or a link list right under an "Archetypes" /
        # "<Class> Archetypes" heading
        lines = md.split("\n")
        level_of = lambda l: len(m.group(1)) if (m := re.match(r"(#{1,6}) ", l)) else 0
        at = next((i for i, l in enumerate(lines) if level_of(l) and ARCHETYPES_SECTION.fullmatch(
            l.lstrip("#").strip())), None)
        if at is not None:
            level = level_of(lines[at])
            for line in lines[at + 1:]:
                lv = level_of(line)
                if lv and lv <= level:
                    break
                text = line.lstrip("#").strip() if lv == level + 1 else \
                    line[2:].strip() if line.startswith("- ") else ""
                if text.startswith("[["):
                    cells.append(re.sub(r"(?<!\\)\|", r"\\|", text))
    # the wiki writes some names as "-[[Antiquarian]]"
    return [re.sub(r"^[-–—]\s*", "", c) for c in cells]


