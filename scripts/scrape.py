def tidy_home(md: str) -> str:
    """Home page clean-up once the mirror stopped tracking the source wiki's front page:
    - drop the "Latest Updates" / "Next Planned Update" news (and the rule under it) and the
      "*Source: ...*" credit line under About the Spheres;
    - fold "Other Systems" into "Other Resources": its linked headings become list entries
      (link - About text), and the blurbs left behind by excluded links go;
    - drop list entries whose link was excluded (e.g. "- - If you play games online ...")."""
    lines = md.split("\n")
    news = [i for i, l in enumerate(lines) if re.match(r"\*\*(Latest Updates|Next Planned Update):\*\*", l)]
    if news:
        end = news[-1] + 1
        while end < len(lines) and lines[end].strip() in ("", "---"):
            end += 1
        lines[news[0]:end] = []
    lines = [l for l in lines if not re.match(r"\*Source: \[[^\]]*\]\([^)]*\)\*$", l.strip())]

    systems = next((i for i, l in enumerate(lines) if l.strip() == "# Other Systems"), None)
    resources = next((i for i, l in enumerate(lines) if l.strip() == "# Other Resources"), None)
    if systems is not None and resources is not None and systems < resources:
        entries, k = [], systems
        while k < resources:
            m = re.match(r"## (\[\[[^\]]+\]\])\s*$", lines[k].strip())
            if m:
                about = next((lines[j].strip() for j in range(k + 1, resources) if lines[j].strip()), "")
                about = re.sub(r"^\*\*About:\*\*\s*", "", about)
                entries.append(f"- {m.group(1)} - {about}" if about and not about.startswith(("<", "---", "#"))
                               else f"- {m.group(1)}")
            k += 1
        start = systems
        while start > 0 and lines[start - 1].strip() in ("", "---"):
            start -= 1
        intro_end = resources + 1
        while intro_end < len(lines) and not lines[intro_end].startswith("- "):
            intro_end += 1
        lines = lines[:start] + [""] + lines[resources:intro_end] + [e for x in entries for e in (x, "")] \
            + lines[intro_end:]
    lines = [l for l in lines if not l.startswith("- - ")]
    # pages the (excluded) Diamond Recreational Studios hub used to link, beside their base pages
    def after(line_re: str, new: list[str]):
        at = next((i for i, l in enumerate(lines) if re.fullmatch(line_re, l.strip())), None)
        if at is None:
            print(f"warning: home: no line {line_re!r}")
        else:
            lines[at + 1:at + 1] = new
    after(r"\[\[Alternate Racial Traits\]\]", ["[[Alternate Racial Traits (DRS)|Alternate Racial Traits]] [DRS]"])
    after(r"\[\[Champion Feats\]\]", ["[[Feats (DRS)|DRS Feats]]"])
    # the Citations Guide is excluded (the citation tags are stripped)
    lines = [l for l in lines if not l.startswith("- [[Citations Guide]]")]
    # the House Rules section's pages are excluded (EXCLUDED_PAGES); drop its heading and intro too
    hr = next((i for i, l in enumerate(lines) if l.strip() == "# House Rules"), None)
    if hr is not None:
        end = next((i for i in range(hr + 1, len(lines)) if re.match(r"# ", lines[i])), len(lines))
        start = hr
        while start > 0 and lines[start - 1].strip() in ("", "---"):
            start -= 1
        lines[start:end] = []
    # the Tools page (hand-written content/Tools.md: Character Builder, Item Crafter) and the Archive
    # head the Other Resources list
    res = next((i for i, l in enumerate(lines) if l.strip() == "# Other Resources"), None)
    if res is not None:
        first = next((i for i in range(res + 1, len(lines)) if lines[i].startswith("- ")), None)
        if first is not None:
            lines[first:first] = ["- [[Tools]] - Resources to help with character or campaign crafting, "
                                  "like the Character Builder and Item Crafter.", "",
                                  f"- [[{ARCHIVE}]] - Retired spheres content", "",
                                  "- [[Using Polished Spheres]] - The rules shared by Diamond Recreational "
                                  "Studios' Polished Spheres releases (Polished Dark, Leadership, Commander and "
                                  "Warleader).", ""]
    md = "\n".join(lines)
    # the citation tags are stripped site-wide (strip_citation_tags), so the note explaining them goes
    md = re.sub(r"\n\*\*Citations Guide:\*\*[^\n]*\n\n?", "\n", md, count=1)
    # links removed from Other Resources leave runs of blank lines behind
    at = md.find("# Other Resources")
    if at >= 0:
        md = md[:at] + re.sub(r"\n{3,}", "\n\n", md[at:])
    return md


def remove_using_row(md: str) -> str:
    """Drop the old row of big "Using Spheres of ..." headings (now in the column headers)."""
    lines = md.split("\n")
    at = next((i for i, l in enumerate(lines) if l.startswith("## [[Using Spheres Of Power")), None)
    if at is None:
        return md
    start = next((i for i in range(at, -1, -1) if lines[i].startswith('<div class="sop-columns"')), None)
    if start is None:
        return md
    depth = 0
    for end in range(start, len(lines)):
        s = lines[end].strip()
        if s.startswith("<div") and not s.endswith("</div>"):
            depth += 1
        elif s == "</div>":
            depth -= 1
            if depth == 0:
                return "\n".join(lines[:start] + lines[end + 1:])
    return md


def split_section(md: str, heading: str) -> tuple[str, list[tuple[str, str]]]:
    """Cut the entries of the '<heading>' section out of a page's markdown.

    Entries are the section's top-level sub-headings (e.g. each monster's "#### Name (CR 8)").
    Returns (page markdown with the entries replaced by a link-list placeholder, [(title, entry
    markdown)]). The page is returned unchanged if the section isn't found or an entry would cut
    through a raw <div> block."""
    lines = md.split("\n")
    level_of = lambda l: len(m.group(1)) if (m := re.match(r"(#{1,6}) ", l)) else 0
    start = next((i for i, l in enumerate(lines)
                  if level_of(l) and l.lstrip("#").strip().lower() == heading.lower()), None)
    if start is None:
        return md, []
    level = level_of(lines[start])
    # the section also ends where its block (e.g. a tab) closes
    end = next((i for i in range(start + 1, len(lines))
                if 0 < level_of(lines[i]) <= level or lines[i].strip() == "</div>"), len(lines))
    section = lines[start + 1:end]
    heads = [i for i, l in enumerate(section) if level_of(l)]
    if not heads:
        return md, []
    entry_level = min(level_of(section[i]) for i in heads)
    starts = [i for i in heads if level_of(section[i]) == entry_level]
    entries = []
    for n, i in enumerate(starts):
        chunk = section[i + 1:starts[n + 1] if n + 1 < len(starts) else len(section)]
        text = "\n".join(chunk)
        if text.count("<div") != text.count("</div>"):
            return md, []
        title = re.sub(r"\[\[([^\]|]*\\?\|)?([^\]]*)\]\]", r"\2", section[i].lstrip("#").strip())
        # sub-headings move up so the entry's own sections start at ##
        shift = entry_level - 1
        body = [("#" * max(2, level_of(l) - shift) + " " + l.lstrip("#").lstrip()) if level_of(l) else l
                for l in chunk]
        entries.append((title, "\n".join(body).strip() + "\n"))
    intro = "\n".join(section[:starts[0]]).rstrip()
    placeholder = "\n".join([lines[start], "", intro, "", "{{SPLIT_LINKS}}", ""]) if intro.strip() \
        else "\n".join([lines[start], "", "{{SPLIT_LINKS}}", ""])
    return "\n".join(lines[:start] + [placeholder] + lines[end:]), entries


# Wild magic: every generator + table pair (the Wild Magic page's Universal / Cantrip / Major
# Event tables and each sphere's own table) is gathered on the Wild Magic page behind a dropdown,
# one panel per table with its roller; the sphere pages link there instead.
WILD_MAGIC_SLUG = "wild-magic"
WILD_MAGIC_CORE_LABELS = {"Universal Wild Magic": "Universal", "Cantrip Wild Magic": "Cantrip",
                          "Major Event": "Major Events"}
ROLL_BLOCK = re.compile(
    r"^#{1,6} (?P<name>[^\n]*?)\s*Generator\n\n<div class=\"sop-roller\"></div>\n\n"
    r"#{1,6} [^\n]*?Table\n\n(?P<table>(?:\|[^\n]*(?:\n|$))+)", re.M)


def wm_id(label: str) -> str:
    return "wm-" + re.sub(r"[^a-z0-9]+", "-", label.lower()).strip("-")


def extract_roll_blocks(md: str) -> tuple[str, list[tuple[str, str]]]:
    """Cut every 'X Generator' + roller + 'X Table' + table block out of the markdown.
    Returns (markdown with {{ROLL:n}} placeholders, [(name, table markdown)])."""
    blocks: list[tuple[str, str]] = []

    def cut(m: re.Match) -> str:
        blocks.append((m.group("name").strip(), m.group("table").rstrip("\n")))
        return f"{{{{ROLL:{len(blocks) - 1}}}}}\n"

    return ROLL_BLOCK.sub(cut, md), blocks


def wild_magic_chooser(core: list[tuple[str, str]], spheres: dict[str, str]) -> str:
    """The Wild Magic page's table chooser: one panel per table (SopRoller turns it into a dropdown;
    Obsidian shows the panels stacked)."""
    parts = ['<div class="sop-wildmagic">', ""]
    panels = [(label, table, "General") for label, table in core] + \
             [(label, spheres[label], "Spheres") for label in sorted(spheres)]
    for label, table, group in panels:
        parts += [f'<div class="sop-wm-panel" id="{wm_id(label)}" data-name="{html.escape(label)}" '
                  f'data-group="{group}">', "", f"**{label}**", "", '<div class="sop-roller"></div>', "",
                  table, "", "</div>", ""]
    parts.append("</div>")
    return "\n".join(parts)


def split_sphere_feats(md: str, sphere: str) -> tuple[str, str]:
    """Cut a sphere page's "<Sphere> Sphere Feats" section out (it moves to its own page).
    Returns (page markdown with the section replaced by a link, feats-page markdown) or (md, "")."""
    lines = md.split("\n")
    level_of = lambda l: len(m.group(1)) if (m := re.match(r"(#{1,6}) ", l)) else 0
    head = rf"#{{1,6}} {re.escape(sphere)} Sphere Feats\s*"
    start = next((i for i, l in enumerate(lines) if re.fullmatch(head, l)), None)
    if start is None:
        return md, ""
    level = level_of(lines[start])
    end = next((i for i in range(start + 1, len(lines))
                if 0 < level_of(lines[i]) <= level or lines[i].strip() == "</div>"), len(lines))
    while end - 1 > start and lines[end - 1].strip() in ("", "---"):
        end -= 1  # trailing divider/blank lines stay on the sphere page
    chunk = lines[start + 1:end]
    text = "\n".join(chunk)
    if text.count("<div") != text.count("</div>"):
        return md, ""
    # the shallowest heading inside (each feat) becomes ##, deeper ones keep their nesting
    inner = min((level_of(l) for l in chunk if level_of(l)), default=level + 1)
    body = [("#" * max(2, level_of(l) - inner + 2) + " " + l.lstrip("#").lstrip()) if level_of(l) else l
            for l in chunk]
    # the section leaves the sphere page entirely (the home page links each sphere's feats page)
    return "\n".join(lines[:start] + lines[end:]), "\n".join(body).strip() + "\n"


def insert_first_tabs(md: str, tabs: list[tuple[str, str]]) -> str:
    """Put extra tabs (label, markdown) in front of a page's existing tab set."""
    lines = md.split("\n")
    first = next((i for i, l in enumerate(lines) if l.startswith('<div class="sop-tab" data-tab=')), None)
    if first is None:
        return md
    block = []
    for label, body in tabs:
        tab_id = re.sub(r"[^a-z0-9]+", "-", label.lower()).strip("-")
        block += [f'<div class="sop-tab" data-tab="{tab_id}">', "",
                  f'<div class="sop-tab-label">{html.escape(label)}</div>', "", body.strip(), "", "</div>", ""]
    return "\n".join(lines[:first] + block + lines[first:])


def tab_set(tabs: list[tuple[str, str]]) -> str:
    """A whole tab set (label, markdown) as .sop-tabs markdown; the first tab opens by default."""
    block = ['<div class="sop-tabs">', ""]
    for label, body in tabs:
        tab_id = re.sub(r"[^a-z0-9]+", "-", label.lower()).strip("-")
        block += [f'<div class="sop-tab" data-tab="{tab_id}">', "",
                  f'<div class="sop-tab-label">{html.escape(label)}</div>', "", body.strip(), "", "</div>", ""]
    return "\n".join(block + ["</div>", ""])


# "note:<page>" extras, applied to finished pages (filled by load_extras). Modes besides merge/after/
# prepend: "tab" (section = a tab label) puts the file before the page's content as a tab of its
# own, the old content becoming an "Ultimate" tab; "replace" (section = "<entry heading> => <tab
# label>") puts it beside one entry the same way. retire_ultimate() then archives the old ones.
NOTE_EXTRAS: dict[str, list[tuple[str, str, str]]] = {}
EXTRA_PAGE_FAMILIES: dict[str, str] = {}  # extras page path -> link-color family


def apply_note_extras() -> int:
    files = {f.stem: f for f in CONTENT.rglob("*.md") if ARCHIVE not in f.relative_to(CONTENT).parts}
    done = 0
    for stem, items in NOTE_EXTRAS.items():
        f = files.get(stem)
        if not f:
            print(f"warning: extras for missing page {stem!r}")
            continue
        text = f.read_text(encoding="utf-8")
        head, body = text.split(GENERATED_MARK, 1) if GENERATED_MARK in text else ("", text)
        body = body.strip("\n")
        tail = ""
        if (m := re.search(r"\n---\n\n\*Archived: [^\n]*\n?$", body)):
            body, tail = body[:m.start()].rstrip(), body[m.start():]
        for mode, section, extra in items:
            if mode == "tab":
                body = tab_set([(section, extra), ("Ultimate", body)]).rstrip()
            elif mode == "replace":
                name, _, label = (s.strip() for s in section.partition("=>"))
                lines = body.split("\n")
                hit = _entry(lines, name)
                if not hit:
                    print(f"warning: extras replace on {stem}: no {name!r}")
                    continue
                start, end, _ = hit
                own = "\n".join(lines[start + 1:end]).strip()
                lines[start + 1:end] = ["", tab_set([(label or "Polished", extra), ("Ultimate", own)])]
                body = "\n".join(lines)
            else:
                body = apply_extras(body, stem, [(mode, section, extra)])
        f.write_text(head + GENERATED_MARK + "\n\n" + re.sub(r"\n{3,}", "\n\n", body) + tail + "\n",
                     encoding="utf-8")
        done += 1
    return done


# Pages whose entries are folded into another page and then dropped: source page -> target page.
# Each "## Section" of the source puts its "####" entries into the target's section of that name,
# alphabetically (the DRS traits page only adds to the categories Traits already has).
PAGE_FOLDS = {
    "Traits (DRS)": "Traits",
}


def fold_pages() -> int:
    files = {f.stem: f for f in CONTENT.rglob("*.md") if ARCHIVE not in f.relative_to(CONTENT).parts}
    moved = 0
    for src_name, dest_name in PAGE_FOLDS.items():
        src, dest = files.get(src_name), files.get(dest_name)
        if not src or not dest:
            print(f"warning: fold {src_name!r} into {dest_name!r}: page missing")
            continue
        sbody = src.read_text(encoding="utf-8").split(GENERATED_MARK, 1)[-1].split("\n")
        text = dest.read_text(encoding="utf-8")
        head, body = text.split(GENERATED_MARK, 1)
        lines = body.split("\n")
        section = None
        entries: list[tuple[str, list[str]]] = []
        for i, l in enumerate(sbody):
            if l.startswith("## "):
                section = l[3:].strip()
            elif l.startswith("#### ") and section:
                end = next((j for j in range(i + 1, len(sbody)) if re.match(r"#{1,4} ", sbody[j])), len(sbody))
                entries.append((section, sbody[i:end]))
        for section, chunk in entries:
            at = next((i for i, l in enumerate(lines) if l.strip() == f"## {section}"), None)
            if at is None:
                print(f"warning: fold {src_name!r}: no section {section!r} on {dest_name}")
                continue
            end = next((j for j in range(at + 1, len(lines)) if re.match(r"#{1,2} ", lines[j])), len(lines))
            name = _norm(chunk[0][5:])
            pos = next((j for j in range(at + 1, end) if lines[j].startswith("#### ")
                        and _norm(lines[j][5:]) > name), end)
            # chunks carry their trailing blank line; one before the next heading keeps them apart
            chunk = [c for c in chunk]
            while chunk and not chunk[-1].strip():
                chunk.pop()
            lines[pos:pos] = chunk + [""]
            moved += 1
        dest.write_text(head + GENERATED_MARK + re.sub(r"\n{3,}", "\n\n", "\n".join(lines)), encoding="utf-8")
        src.unlink()
    return moved


def load_extras() -> tuple[dict[str, list[tuple[str, str, str]]], list[tuple[str, str, str]]]:
    """extras/*.md -> ({page slug: [(mode, section, body)]}, [(note path, title, body)])."""
    merges: dict[str, list[tuple[str, str, str]]] = {}
    new_pages: list[tuple[str, str, str]] = []
    for f in sorted(EXTRAS.glob("*.md")) if EXTRAS.is_dir() else []:
        text = f.read_text(encoding="utf-8")
        m = re.match(r"\s*<!--\s*extras:\s*([^|]+?)\s*\|\s*([^|]+?)\s*\|\s*(.+?)\s*-->\s*\n", text)
        if not m:
            print(f"warning: extras/{f.name} has no header")
            continue
        body = text[m.end():].strip()
        if m.group(1) == "page":
            # "page | <path> | <title> | <family>": an optional link-color family (e.g. might)
            title, _, fam = (x.strip() for x in m.group(3).partition("|"))
            new_pages.append((m.group(2), title, body))
            if fam:
                EXTRA_PAGE_FAMILIES[f"{m.group(2)}.md"] = fam
        elif m.group(1).startswith("note:"):
            # applied to the finished page of that name after everything is written: apply_note_extras
            NOTE_EXTRAS.setdefault(m.group(1)[5:].strip(), []).append((m.group(2), m.group(3), body))
        else:
            merges.setdefault(m.group(1), []).append((m.group(2), m.group(3), body))
    return merges, new_pages


def _norm(s: str) -> str:
    return re.sub(r"[^a-z0-9]+", " ", s.replace("’", "'").lower()).strip()


def _entry_name(heading: str) -> str:
    """A heading's sort/compare key: wikilinks unwrapped, [tags] dropped, normalized."""
    text = re.sub(r"\[\[(?:[^\]|]*\|)?([^\]]*)\]\]", r"\1", heading.lstrip("#"))
    return _norm(re.sub(r"\[[^\]]*\]", "", text))


def _section_span(lines: list[str], section: str) -> tuple[int, int, int] | None:
    """(heading line, end line, heading level) of the first heading or tab label named section;
    a tab's level is 0. The section ends at the next heading of the same or a higher level, or
    at the end of the tab it sits in."""
    if section == "(page)":  # the whole page (for entries that sit under no heading of their own)
        return -1, len(lines), 0
    # "## Type Talents": only a heading of that level (Conjuration has a "### Type Talents" rules
    # note before its "## Type Talents" section)
    at_level = len(m.group(1)) if (m := re.match(r"(#{1,6}) ", section)) else None
    want = _norm(section.lstrip("# "))
    for i, l in enumerate(lines):
        s = l.strip()
        m = re.match(r"(#{1,6}) (.+)$", s)
        tab = re.fullmatch(r'<div class="sop-tab-label">(.*)</div>', s)
        if m and _norm(m.group(2)) == want and (at_level is None or len(m.group(1)) == at_level):
            level = len(m.group(1))
        elif tab and _norm(html.unescape(tab.group(1))) == want:
            level = 0
        else:
            continue
        depth, end = 0, i + 1
        while end < len(lines):
            t = lines[end].strip()
            h = re.match(r"(#{1,6}) ", t)
            if h and level and len(h.group(1)) <= level and depth == 0:
                break
            if t.startswith("<div") and not t.endswith("</div>"):
                depth += 1
            elif t == "</div>":
                if depth == 0:
                    break
                depth -= 1
            end += 1
        while end > i + 1 and lines[end - 1].strip() in ("", "---"):
            end -= 1
        return i, end, level
    return None


def apply_extras(md: str, slug: str, extras: list[tuple[str, str, str]]) -> str:
    for mode, section, body in extras:
        lines = md.split("\n")
        span = _section_span(lines, section)
        if span is None:
            print(f"warning: extras for {slug}: no section {section!r}")
            continue
        start, end, level = span
        if mode == "after":
            md = "\n".join(lines[:end] + ["", "---", "", body, ""] + lines[end:])
        elif mode == "append":  # at the end of the section itself (no divider)
            md = "\n".join(lines[:end] + ["", body, ""] + lines[end:])
        elif mode == "prepend":
            at = next((k for k in range(start + 1, end) if re.match(r"#{1,6} ", lines[k])), end)
            md = "\n".join(lines[:at] + [body, ""] + lines[at:])
        elif mode == "merge":
            blines = body.split("\n")
            heads = [k for k, l in enumerate(blines) if re.match(r"#{1,6} ", l)]
            if not heads:
                continue
            elevel = len(blines[heads[0]].split(" ")[0])
            entries = [blines[a:b] for a, b in zip(heads, heads[1:] + [len(blines)])]
            for entry in entries:
                name = _entry_name(entry[0])
                lines = md.split("\n")
                start, end, _ = _section_span(lines, section)
                # sibling entries: same-level headings in the section's first run of them
                sibs, seen = [], False
                for k in range(start + 1, end):
                    h = re.match(r"(#{1,6}) (.+)$", lines[k])
                    if not h:
                        continue
                    if len(h.group(1)) == elevel:
                        sibs.append(k)
                        seen = True
                    elif len(h.group(1)) < elevel and seen:
                        end = k
                        break
                at = next((k for k in sibs if _entry_name(lines[k]) > name), None)
                if at is None:
                    at = end
                    while at > start + 1 and lines[at - 1].strip() in ("", "---"):
                        at -= 1
                    md = "\n".join(lines[:at] + ["", *entry, ""] + lines[at:])
                else:
                    md = "\n".join(lines[:at] + [*entry, ""] + lines[at:])
    return md


def drop_entries(md: str, section: str, names: list[str]) -> str:
    """Remove '**Name ...:**' paragraphs (and their plain continuation paragraphs) in a section."""
    lines = md.split("\n")
    span = _section_span(lines, section)
    if span is None:
        return md
    start, end, _ = span
    wanted = {_norm(n) for n in names}
    keep, dropping, dropped = [], False, set()
    for k in range(start + 1, end):
        s = lines[k].strip()
        lead = re.match(r"\*\*([^*(:]+?)\s*(?:\(|:|\*\*)", s)
        if lead or s.startswith("#"):
            dropping = bool(lead) and _norm(lead.group(1)) in wanted
            if dropping:
                dropped.add(_norm(lead.group(1)))
        if not dropping:
            keep.append(lines[k])
    for n in wanted - dropped:
        print(f"warning: drop entry {n!r} not found in {section!r}")
    return "\n".join(lines[:start + 1] + keep + lines[end:])


def drop_empty_columns(md: str) -> str:
    """Remove sop-col columns left with nothing but dividers, and fix each grid's --cols count."""
    md = re.sub(r'<div class="sop-col">\s*(?:---\s*)*</div>\s*', "", md)
    out, lines = [], md.split("\n")
    for i, l in enumerate(lines):
        m = re.match(r'(<div class="sop-columns" style="--cols: )\d+(">)', l.strip())
        if m:
            depth, cols = 0, 0
            for l2 in lines[i:]:
                s = l2.strip()
                if s.startswith("<div") and not s.endswith("</div>"):
                    depth += 1
                    cols += depth == 2 and s == '<div class="sop-col">'
                elif s == "</div>":
                    depth -= 1
                    if depth == 0:
                        break
            l = re.sub(r"--cols: \d+", f"--cols: {max(cols, 1)}", l)
        out.append(l)
    return "\n".join(out)


def split_tab(md: str, tab_id: str) -> tuple[str, str | None]:
    """Cut the first '<div class="sop-tab" data-tab="<tab_id>">' out of a page; return (rest,
    the tab's markdown without its label). A tab set left with a single tab is unwrapped."""
    lines = md.split("\n")
    opens: list[int] = []
    match: dict[int, int] = {}   # div open line -> its close line
    parent: dict[int, int | None] = {}
    for i, l in enumerate(lines):
        s = l.strip()
        if s.startswith("<div") and not s.endswith("</div>"):
            parent[i] = opens[-1] if opens else None
            opens.append(i)
        elif s == "</div>" and opens:
            match[opens.pop()] = i
    tab = next((i for i in match if lines[i].strip() == f'<div class="sop-tab" data-tab="{tab_id}">'), None)
    if tab is None:
        return md, None
    end = match[tab]
    inner = [l for l in lines[tab + 1:end] if not l.strip().startswith('<div class="sop-tab-label">')]
    drop = set(range(tab, end + 1))
    tabs = parent.get(tab)
    if tabs is not None:
        rest = [i for i in match if parent.get(i) == tabs and i != tab
                and lines[i].strip().startswith('<div class="sop-tab"')]
        if len(rest) == 1:  # one tab left: no tab set needed
            only = rest[0]
            drop |= {tabs, match[tabs], only, match[only]}
            drop |= {k for k in range(only, match[only])
                     if lines[k].strip().startswith('<div class="sop-tab-label">')
                     and k == next(j for j in range(only + 1, match[only]) if lines[j].strip())}
    out = [l for i, l in enumerate(lines) if i not in drop]
    return re.sub(r"\n{3,}", "\n\n", "\n".join(out)), "\n".join(inner).strip()


def unwrap_lone_tabs(md: str, labels: set[str] | None = None) -> str:
    """Drop the tab-set wrapper around a set holding a single tab (whose label is in labels, if given)."""
    while True:
        lines = md.split("\n")
        opens: list[int] = []
        match: dict[int, int] = {}
        parent: dict[int, int | None] = {}
        for i, l in enumerate(lines):
            s = l.strip()
            if s.startswith("<div") and not s.endswith("</div>"):
                parent[i] = opens[-1] if opens else None
                opens.append(i)
            elif s == "</div>" and opens:
                match[opens.pop()] = i
        drop = None
        for t in sorted(match):
            if lines[t].strip() != '<div class="sop-tabs">':
                continue
            kids = [i for i in match if parent.get(i) == t and lines[i].strip().startswith('<div class="sop-tab"')]
            if len(kids) != 1:
                continue
            k = kids[0]
            lab = next((j for j in range(k + 1, match[k]) if lines[j].strip()), None)
            m = re.fullmatch(r'<div class="sop-tab-label">(.*)</div>', lines[lab].strip()) if lab else None
            if m and (labels is None or html.unescape(m.group(1)) in labels):
                drop = {t, match[t], k, match[k], lab}
                break
        if drop is None:
            return md
        md = re.sub(r"\n{3,}", "\n\n", "\n".join(l for i, l in enumerate(lines) if i not in drop))


def original_spheres_index(home: str, archived: dict[str, tuple[str, str]]) -> str:
    """The Original Spheres page: the archived pages grouped under the home page's own section
    titles, in home order (each page where home first links it), the rest under Other Pages."""
    ctx, groups, placed = "Other", {}, set()
    for line in home.split("\n"):
        s = line.strip()
        if m := re.match(r"#{2,3} (.+)$", s):
            ctx = m.group(1)
        elif m := re.match(r"\*\*([^*]+)\*\*(?:\s*\*\(.*\)\*)?$", s):
            ctx = m.group(1)
        else:
            for t in re.findall(r"\[\[([^\]|#\\]+)", s):
                if t in archived and t not in placed:
                    placed.add(t)
                    groups.setdefault(ctx, []).append(t)
            continue
        ctx = re.sub(r"\s*\*\(.*?\)\*", "", re.sub(r"\[\[(?:[^\]|]*\|)?([^\]]*)\]\]", r"\1", ctx)).strip()
    for t in sorted(set(archived) - placed):
        groups.setdefault("Other Pages", []).append(t)
    out = ["The original (pre-*Ultimate*) versions of Spheres of Power pages, as they appeared before "
           "*Ultimate Spheres of Power*. Kept for reference; they are not part of the current rules "
           "and are left out of search.", "", '<div class="sop-spheres">', ""]
    for title, names in groups.items():
        out += [f"**{title}**", ""]
        out += [f"- [[{archived[n][0]}|{archived[n][1]}]]" for n in names]
        out.append("")
    return "\n".join(out + ["</div>", ""])


def tab_section(md: str, heading: str, label: str, tab_md: str, own_label: str) -> str:
    """Wrap the body of the first '<#..> heading' section in a tab set: (label, tab_md) first,
    then the section's own body as (own_label). The section ends at the next heading of the same
    or a higher level, or at the end of the tab it sits in."""
    lines = md.split("\n")
    at = next((i for i, l in enumerate(lines) if re.fullmatch(rf"(#{{1,6}}) {re.escape(heading)}", l.strip())), None)
    if at is None:
        print(f"warning: section tab: no '{heading}' section")
        return md
    level = len(lines[at].strip().split(" ")[0])
    end = at + 1
    while end < len(lines):
        m = re.match(r"(#{1,6}) ", lines[end])
        if (m and len(m.group(1)) <= level) or lines[end].strip().startswith(("<div", "</div>")):
            break
        end += 1
    own = "\n".join(lines[at + 1:end]).strip()
    return "\n".join(lines[:at + 1] + ["", tab_set([(label, tab_md), (own_label, own)])] + lines[end:])


def drop_merged_links(md: str, merges: list[tuple[str, str]]) -> str:
    """'[[Dark]] | [[Dark|Polished Dark]] [DRS]' -> '[[Dark]]' once Polished Dark is a tab of Dark."""
    for target, label in merges:
        # [ \t] only: the match must not run past the end of the line into the next entry
        md = re.sub(rf"[ \t]*\|[ \t]*\[\[{re.escape(target)}\|{re.escape(label)}\]\](?:[ \t]*\[[^\]\n]*\])*",
                    "", md)
    return md


DRAWBACKS_HEADING = "Sphere-Specific Drawbacks"
# Pages whose Sphere-Specific Drawbacks section is split into one page per sphere, with the
# title of the overview page that links them all.
DRAWBACK_SOURCES = {
    "casting-traditions": "Sphere-Specific Drawbacks",          # magic spheres
    "martial-traditions": "Martial Sphere-Specific Drawbacks",  # combat spheres
}


def cut_section(md: str, heading: str) -> tuple[str, str]:
    """Remove the section with this exact heading text; return (rest, its body with the shallowest
    inner heading level normalized to ##). The section ends at a heading of the same or higher
    level or at the end of its block (</div>)."""
    lines = md.split("\n")
    level_of = lambda l: len(m.group(1)) if (m := re.match(r"(#{1,6}) ", l)) else 0
    start = next((i for i, l in enumerate(lines) if level_of(l) and l.lstrip("#").strip() == heading), None)
    if start is None:
        return md, ""
    level = level_of(lines[start])
    end = next((i for i in range(start + 1, len(lines))
                if 0 < level_of(lines[i]) <= level or lines[i].strip() == "</div>"), len(lines))
    chunk = lines[start + 1:end]
    if "\n".join(chunk).count("<div") != "\n".join(chunk).count("</div>"):
        return md, ""
    inner = min((level_of(l) for l in chunk if level_of(l)), default=level + 1)
    body = [("#" * max(2, level_of(l) - inner + 2) + " " + l.lstrip("#").lstrip()) if level_of(l) else l
            for l in chunk]
    return "\n".join(lines[:start] + lines[end:]), "\n".join(body).strip()


def split_drawbacks(md: str, overview: str = DRAWBACKS_HEADING) -> tuple[str, str, list[tuple[str, str]]]:
    """Casting Traditions' "Sphere-Specific Drawbacks" section: one "### [[Sphere]]" group of
    "#### Drawback" entries per sphere. Returns (page markdown with the groups replaced by a link
    to the overview page, the section's intro text, [(sphere note name, that sphere's entries)])."""
    lines = md.split("\n")
    level_of = lambda l: len(m.group(1)) if (m := re.match(r"(#{1,6}) ", l)) else 0
    start = next((i for i, l in enumerate(lines)
                  if level_of(l) and l.lstrip("#").strip() == DRAWBACKS_HEADING), None)
    if start is None:
        return md, "", []
    level = level_of(lines[start])
    end = next((i for i in range(start + 1, len(lines))
                if 0 < level_of(lines[i]) <= level or lines[i].strip() == "</div>"), len(lines))
    section = lines[start + 1:end]
    groups = [i for i, l in enumerate(section) if level_of(l) == level + 1]
    if not groups or "\n".join(section).count("<div") != "\n".join(section).count("</div>"):
        return md, "", []
    intro = "\n".join(section[:groups[0]]).strip()
    spheres = []
    for n, i in enumerate(groups):
        m = re.search(r"\[\[([^\]|#]+)", section[i])
        name = m.group(1) if m else section[i].lstrip("#").strip()
        chunk = section[i + 1:groups[n + 1] if n + 1 < len(groups) else len(section)]
        inner = min((level_of(l) for l in chunk if level_of(l)), default=level + 2)
        body = [("#" * max(2, level_of(l) - inner + 2) + " " + l.lstrip("#").lstrip()) if level_of(l) else l
                for l in chunk]
        if any(level_of(l) for l in body):  # skip groups left empty (e.g. "Universal" after SM—)
            spheres.append((name, "\n".join(body).strip()))
    keep = [lines[start], "", intro, "",
            f"*Each sphere's drawbacks are on their own page: see [[{overview}]].*", ""]
    return "\n".join(lines[:start] + keep + lines[end:]), intro, spheres


def add_feats_links(home_md: str, feats: dict[str, str], drawbacks: dict[str, str] | None = None) -> str:
    """Home page Magic Spheres list: "[[Alteration]]" -> "[[Alteration]] | [[Alteration Sphere Feats|Feats]]"."""
    out, inside = [], False
    for line in home_md.split("\n"):
        if line.strip().startswith(("**Magic Spheres**", "**Skill Spheres**", "**Combat Spheres**")):
            inside = True
        elif inside and (re.fullmatch(r"\*\*[^*]+\*\*", line.strip()) or line.strip() in ("---", "</div>")):
            inside = False
        if inside:
            # "[[Alchemy]]" or "[[Warleader (warleader-sphere)|Warleader]]"
            m = re.match(r"\[\[([^\]|#]+)(?:\|[^\]]*)?\]\]", line)
            if m:
                extra = ""
                if m.group(1) in feats:
                    extra += f" | [[{feats[m.group(1)]}|Feats]]"
                if drawbacks and m.group(1) in drawbacks:
                    extra += f" | [[{drawbacks[m.group(1)]}|Drawbacks]]"
                line = m.group(0) + extra + line[m.end():]
        out.append(line)
    return "\n".join(out)


def set_column_counts(md: str) -> str:
    """Tag each .sop-columns grid with --cols: the number of side-by-side columns it holds.

    Columns containing a markdown table span the full row (see custom.scss), so they don't count;
    the CSS uses --cols to avoid creating empty tracks on wide screens."""
    lines = md.split("\n")
    stack: list[list] = []  # ["grid", line_idx, narrow, total] / ["col", has_table]
    for i, line in enumerate(lines):
        s = line.strip()
        if s.startswith('<div class="sop-columns"'):
            stack.append(["grid", i, 0, 0])
        elif s == '<div class="sop-col">':
            stack.append(["col", False])
        elif s.startswith("<div") and not s.endswith("</div>"):
            stack.append(["other"])  # e.g. tabs; one-line tab labels open and close on one line
        elif s.startswith("| ---") and stack:
            col = next((c for c in reversed(stack) if c[0] == "col"), None)
            if col:
                col[1] = True
        elif s == "</div>" and stack:
            top = stack.pop()
            if top[0] == "other":
                continue
            if top[0] == "col":
                grid = next((g for g in reversed(stack) if g[0] == "grid"), None)
                if grid:
                    grid[3] += 1
                    grid[2] += 0 if top[1] else 1
            else:
                n = top[2] or top[3] or 1
                lines[top[1]] = f'<div class="sop-columns" style="--cols: {n}">'
    return "\n".join(lines)


ARCHETYPES_HEADING = re.compile(r"\s*archetypes\s*", re.I)


def archetype_runs(body: Tag) -> list[tuple[Tag, list[tuple[Tag, list[Tag]]]]]:
    """Class pages list archetypes as an 'Archetypes' heading followed by one sub-heading per
    archetype (a link + tags) with a short description paragraph or two. Returns
    (archetypes heading, [(entry heading, description paragraphs)]) for each such section whose
    entries are all that simple; anything more complex is left alone."""
    is_h = lambda el: isinstance(el, Tag) and re.fullmatch(r"h[1-6]", el.name or "")
    runs = []
    for h in body.find_all(re.compile(r"^h[1-6]$")):
        if not ARCHETYPES_HEADING.fullmatch(h.get_text(" ", strip=True)):
            continue
        level = int(h.name[1])
        sib = h.find_next_sibling()
        while sib is not None and not is_h(sib) and sib.name != "hr":  # intro text stays as is
            sib = sib.find_next_sibling()
        entries, simple = [], True
        while sib is not None and is_h(sib) and int(sib.name[1]) > level:
            if not sib.find("a", href=True):
                break
            descs, nxt = [], sib.find_next_sibling()
            while nxt is not None and not is_h(nxt) and nxt.name != "hr":
                descs.append(nxt)
                nxt = nxt.find_next_sibling()
            if len(descs) > 3 or any(d.name != "p" for d in descs):
                simple = False
                break
            entries.append((sib, descs))
            sib = nxt
        if simple and entries:
            runs.append((h, entries))
    return runs


def archetype_section_tables(body: Tag, soup_factory) -> None:
    """Replace simple archetype sections with an Archetype | Description table."""
    for _, entries in archetype_runs(body):
        table = soup_factory.new_tag("table", attrs={"class": "wiki-content-table"})
        header = soup_factory.new_tag("tr")
        for label in ("Archetype", "Description"):
            th = soup_factory.new_tag("th")
            th.string = label
            header.append(th)
        table.append(header)
        for heading, descs in entries:
            row = soup_factory.new_tag("tr")
            name, desc = soup_factory.new_tag("td"), soup_factory.new_tag("td")
            for child in list(heading.contents):
                name.append(child)
            for i, d in enumerate(descs):
                if i:
                    desc.append(soup_factory.new_tag("br"))
                for child in list(d.contents):
                    desc.append(child)
            row.append(name)
            row.append(desc)
            table.append(row)
        entries[0][0].insert_before(table)
        for heading, descs in entries:
            heading.decompose()
            for d in descs:
                d.decompose()


