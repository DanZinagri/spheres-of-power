def clean_filename(name: str) -> str:
    name = re.sub(r'[\\/:*?"<>|#^\[\]]', "", name)  # illegal on Windows or meaningful to Obsidian links
    name = re.sub(r"\s+", " ", name).strip(" .")
    return name[:120] or "untitled"


class Page:
    def __init__(self, slug: str, html: str):
        self.slug = slug
        soup = BeautifulSoup(html, "lxml")
        # new tags must come from this same document: mixing in tags from another
        # BeautifulSoup leaves the element chain inconsistent and later find_all() calls skip nodes
        self.soup = soup
        t = soup.select_one("#page-title")
        self.title = t.get_text(" ", strip=True) if t else ""
        if not self.title:
            self.title = slug.split(":")[-1].replace("-", " ").title()
        if slug == "start":
            self.title = "Spheres of Power Wiki"
        elif slug == "nav:side":
            self.title = "Wiki Navigation"
        elif slug == "legal:start":
            self.title = "Legal and Open Game License"
        crumbs = soup.select("#breadcrumbs a")
        self.parents = [a["href"].strip("/") for a in crumbs if a.get("href", "").startswith("/")]
        self.parents = [p for p in self.parents if p != "start"]
        self.tags = [a.get_text(strip=True) for a in soup.select(".page-tags a")
                     if a.get_text(strip=True) and not a.get_text(strip=True).startswith("_")]
        self.body = soup.select_one("#page-content")
        # anchor id -> heading text, so cross-page #toc links can become [[Page#Heading]]
        self.anchors: dict[str, str] = {}
        if self.body:
            for h in self.body.find_all(re.compile("^h[1-6]$")):
                # headings of excluded-tag ([LG]) entries get pruned, so links lose the #fragment
                if h.get("id") and not _has_excluded_tag(h.get_text(" ", strip=True)):
                    self.anchors[h["id"]] = heading_text(h)
            for a in self.body.find_all("a", attrs={"name": True}):
                nxt = a.find_next(re.compile("^h[1-6]$"))
                if nxt:
                    self.anchors[a["name"]] = heading_text(nxt)
            # archetype entry headings become table rows; links to them land on the section
            for section, entries in archetype_runs(self.body):
                for heading, _ in entries:
                    if heading.get("id"):
                        self.anchors[heading["id"]] = heading_text(section)
        # (target slug, family) for every link the wiki wrapped in a product-line color
        self.colored: list[tuple[str, str]] = []
        if self.body:
            for sp in self.body.find_all("span", style=re.compile("color")):
                m = re.search(r"color:\s*(#[0-9a-fA-F]{6})", sp["style"])
                fam = COLOR_FAMILIES.get(m.group(1).lower()) if m else None
                if not fam:
                    continue
                links = sp.find_all("a", href=True)
                outer = sp.find_parent("a", href=True)
                for a in links + ([outer] if outer else []):
                    target = internal_slug(a["href"])
                    if target:
                        self.colored.append((target, fam))
        self.folder = ""
        self.filename = ""


def internal_slug(href: str) -> str | None:
    """Wikidot page slug an href points to, or None for external/file/anchor links."""
    if not href or href.startswith(("#", "javascript:")):
        return None
    parsed = urllib.parse.urlparse(href)
    if parsed.netloc and not parsed.netloc.endswith("spheresofpower.wikidot.com"):
        return None
    if "local--files" in parsed.path:
        return None
    return urllib.parse.unquote(parsed.path.strip("/")).lower() or "start"


def heading_text(h: Tag) -> str:
    return re.sub(r"[#^\[\]|]", "", h.get_text(" ", strip=True)).strip()


class WikiConverter(MarkdownConverter):
    """markdownify with wikidot-aware link/table/image handling."""

    def __init__(self, page: Page, pages: dict[str, Page], images: dict[str, str],
                 redirects: dict[str, Page] | None = None, **kw):
        super().__init__(heading_style="ATX", bullets="-", escape_underscores=False,
                         escape_asterisks=False, **kw)
        self.page, self.pages, self.images = page, pages, images
        self.redirects = redirects or {}

    # --- links
    def convert_a(self, el, text, *args, **kw):
        href = el.get("href", "")
        text = text.strip()
        if not href or href.startswith("javascript:"):
            return text
        if href.startswith("#"):
            target = self.page.anchors.get(href[1:])
            return f"[[#{target}|{text}]]" if target else text
        parsed = urllib.parse.urlparse(href)
        internal = (not parsed.netloc) or parsed.netloc.endswith("spheresofpower.wikidot.com")
        if internal and "local--files" not in parsed.path:
            slug = urllib.parse.unquote(parsed.path.strip("/")) or "start"
            slug = slug.lower()
            target = self.pages.get(slug) or self.redirects.get(slug)
            if target:
                frag = ""
                if parsed.fragment:
                    h = target.anchors.get(parsed.fragment)
                    frag = f"#{h}" if h else ""
                label = text.replace("|", "\\|").replace("[", "(").replace("]", ")")
                if not label or (label == target.filename and not frag):
                    return f"[[{target.filename}{frag}]]"
                return f"[[{target.filename}{frag}|{label}]]"
            # links to pages that don't exist on the wiki ("red links") -> plain text
            if not parsed.netloc:
                return text
        if not text and el.find("img"):
            return ""  # link around a dropped image (cover art, banners)
        if not href.startswith("http"):
            href = SITE + href
        return f"[{text}]({href})" if text else f"<{href}>"

    # --- images: only kept when downloaded with --images; otherwise dropped entirely
    def convert_img(self, el, text, *args, **kw):
        src = el.get("src", "")
        if src in self.images:
            return f"![[{self.images[src]}]]"
        return ""

    # --- tables: keep cells single-line so the markdown table survives
    def convert_td(self, el, text, *args, **kw):
        text = re.sub(r"\s*\n\s*", " <br> ", text.strip()).replace("|", "\\|")
        text = re.sub(r"(\s*<br>\s*)+$", "", text)
        colspan = int(el.get("colspan", 1) or 1)
        return " " + text + " |" + " |" * (colspan - 1)

    convert_th = convert_td

    # --- column layouts: raw HTML wrappers on their own lines (blank-line separated) so the
    # markdown between them still parses; Quartz styles .sop-columns as a grid, Obsidian
    # simply shows the columns stacked.
    def convert_div(self, el, text, *args, **kw):
        cls = el.get("class") or []
        if "sop-roller" in cls:
            return '\n\n<div class="sop-roller"></div>\n\n'
        if "sop-tab-label" in cls:
            return f'\n\n<div class="sop-tab-label">{html.escape(el.get_text(" ", strip=True))}</div>\n\n'
        for name in ("sop-columns", "sop-col", "sop-tabs", "sop-tab"):
            if name in cls:
                if not text.strip():
                    return ""  # every column/link in it was excluded
                extra = f' data-tab="{html.escape(el["data-tab"])}"' if el.get("data-tab") else ""
                return f'\n\n<div class="{name}"{extra}>\n\n{text.strip()}\n\n</div>\n\n'
        return f"\n\n{text}\n\n" if text.strip() else ""


def group_columns(body: Tag, soup_factory) -> None:
    """Wikidot [[div style="float:left; width:N%"]] side-by-side blocks -> .sop-columns/.sop-col."""
    floating = lambda el: isinstance(el, Tag) and el.name == "div" and \
        re.search(r"float:\s*(left|right)", el.get("style", ""))
    for start in body.find_all(floating):
        if start.parent is None or "sop-col" in (start.get("class") or []):
            continue
        prev = start.find_previous_sibling(True)
        if prev is not None and floating(prev):
            continue  # not the first of its run
        run = [start]
        nxt = start.find_next_sibling(True)
        while nxt is not None and floating(nxt):
            run.append(nxt)
            nxt = nxt.find_next_sibling(True)
        if len(run) < 2:
            continue
        wrapper = soup_factory.new_tag("div", attrs={"class": "sop-columns"})
        start.insert_before(wrapper)
        for col in run:
            col.attrs = {"class": "sop-col"}
            wrapper.append(col.extract())


def _only_tags_besides(el: Tag, links: list[Tag]) -> bool:
    """True when el's text is just the given links' text plus [tags] / separators."""
    return _only_tags_besides_text(el.get_text(" ", strip=True), links)


def _only_tags_besides_text(text: str, links: list[Tag]) -> bool:
    text = " ".join(text.split())
    for a in links:
        text = text.replace(" ".join(a.get_text(" ", strip=True).split()), "", 1)
    text = re.sub(r"\[[^\]]*\]", "", text)
    text = re.sub(r"\(\s*[A-Z0-9/—–-]{2,12}\s*\)", "", text)  # short tags like (3PP), (SM—)
    return not text.strip(" ,|·:;-–—()")


def prune_excluded_entries(body: Tag, excluded: set[str]) -> None:
    """On any page, drop entries that exist only for excluded content: a heading that is just
    a link to it (plus tags like [CS] [LG]) together with its section, and list items or
    paragraphs that are only such a link. Links to it inside prose are left as plain text."""
    # decide which tables are navboxes/layout before pruning empties cells and skews the heuristic
    for table in body.find_all("table"):
        if is_layout_table(table):
            table["data-layout"] = "1"
    is_heading = lambda el: isinstance(el, Tag) and re.fullmatch(r"h[1-6]", el.name or "")
    for h in body.find_all(re.compile(r"^h[1-6]$")):
        if h.parent is None:
            continue
        links = h.find_all("a", href=True)
        if not links or any(internal_slug(a["href"]) not in excluded for a in links):
            continue
        if not _only_tags_besides(h, links):
            continue
        level = int(h.name[1])
        sib = h.find_next_sibling()
        while sib is not None:
            if (is_heading(sib) and int(sib.name[1]) <= level) or sib.name == "hr":
                break
            nxt = sib.find_next_sibling()
            sib.decompose()
            sib = nxt
        h.decompose()
    # lines inside <br>-separated blocks ("- [[Bear]]<br>- [[Technomancy]] [3PP]<br>...")
    is_br = lambda n: isinstance(n, Tag) and n.name == "br"
    for a in body.find_all("a", href=True):
        if a.parent is None or internal_slug(a["href"]) not in excluded:
            continue
        line, prev, nxt = [a], a.previous_sibling, a.next_sibling
        while prev is not None and not is_br(prev):
            line.insert(0, prev)
            prev = prev.previous_sibling
        while nxt is not None and not is_br(nxt):
            line.append(nxt)
            nxt = nxt.next_sibling
        if prev is None and nxt is None:
            continue  # not a <br>-separated line; whole elements are handled below
        if any(isinstance(n, Tag) and n is not a and (n.name == "a" or n.find("a")) for n in line):
            continue  # the line has other links too
        if not _only_tags_besides_text("".join(
                n.get_text(" ") if isinstance(n, Tag) else str(n) for n in line), [a]):
            continue
        for n in line:
            n.extract()
        (nxt if nxt is not None else prev).extract()  # and one of the surrounding <br>s

    touched_tables = []
    for el in body.find_all(["li", "p", "dt", "td", "th"]):
        if el.parent is None:
            continue
        links = el.find_all("a", href=True)
        only_excluded = links and all(internal_slug(a["href"]) in excluded for a in links)
        if only_excluded and _only_tags_besides(el, links):
            if el.name in ("td", "th"):
                table = el.find_parent("table")
                tr = el.find_parent("tr")
                first = tr.find(["td", "th"], recursive=False) if tr else None
                if table is not None and not table.get("data-layout") and first is el:
                    tr.decompose()  # data table row named by the excluded entry (name | text)
                    continue
                el.clear()  # keep the cell so table columns stay aligned
                if table is not None and table not in touched_tables:
                    touched_tables.append(table)
            else:
                el.decompose()

    # tables (mostly navboxes) that lost cells: drop rows left empty, and the whole table when
    # none of its links survive (e.g. a navbox for an excluded book)
    for table in touched_tables:
        if table.parent is None:
            continue
        if not table.find("a", href=True):
            table.decompose()
            continue
        for tr in table.find_all("tr"):
            if not tr.get_text(strip=True) and not tr.find("img"):
                tr.decompose()
        # section labels ("Races") whose items were all removed: a link-less single-cell row
        # followed by another such label row, or by nothing
        is_label = lambda tr: tr is not None and not tr.find("a") and \
            len([c for c in tr.find_all(["td", "th"], recursive=False) if c.get_text(strip=True)]) == 1
        rows = table.find_all("tr")
        for i, tr in enumerate(rows):
            nxt = rows[i + 1] if i + 1 < len(rows) else None
            if is_label(tr) and (nxt is None or is_label(nxt)):
                tr.decompose()


def _has_excluded_tag(text: str) -> bool:
    """Tags appear as "[SM—]", "(SM—)", "[CS] [LG]", "[3PP/LG]", or bare at the end of a title
    ("Polymath SM—")."""
    token = lambda t: rf"(^|[^A-Za-z]){re.escape(t)}([^A-Za-z]|$)"
    for tag in re.findall(r"[\[(]([^\])]*)[\])]", text):
        if any(re.search(token(t), tag) for t in EXCLUDED_TAGS):
            return True
    return any(re.search(rf"\s{re.escape(t)}\s*$", text) for t in EXCLUDED_TAGS)


def tagged_pages(pages: dict[str, "Page"]) -> set[str]:
    """Slugs of pages marked with an excluded tag: in their own title, or as the tag right after
    a link to them anywhere on the wiki ("[[Nanocyte]] [CS] [LG]")."""
    found = {s for s, p in pages.items() if _has_excluded_tag(p.title)}
    for p in pages.values():
        if not p.body:
            continue
        for a in p.body.find_all("a", href=True):
            target = internal_slug(a["href"])
            if not target or target in found or target not in pages:
                continue
            after = ""
            for el in a.next_elements:
                if el is a or (isinstance(el, (Tag, NavigableString)) and a in el.parents):
                    continue
                if getattr(el, "name", None) in ("a", "br", "p", "li", "td", "div"):
                    break
                if isinstance(el, NavigableString):
                    after += str(el)
                if len(after) > 40:
                    break
            m = re.match(r"\s*((?:[\[(][^\])]*[\])]\s*)+)", after)
            if m and _has_excluded_tag(m.group(1)):
                found.add(target)
    return found


def _line_text(nodes: list) -> str:
    """Text of the nodes up to the first <br>."""
    out = []
    for n in nodes:
        if isinstance(n, Tag) and n.name == "br":
            break
        out.append(n.get_text(" ") if isinstance(n, Tag) else str(n))
    return " ".join("".join(out).split())


def _prune_tagged_lines(el: Tag) -> None:
    """Inside a <br>-separated block, drop each later line that starts with a tagged label."""
    children = list(el.children)
    breaks = [i for i, c in enumerate(children) if isinstance(c, Tag) and c.name == "br"]
    for i in reversed(breaks):  # back to front so indexes stay valid
        line = children[i + 1:]
        stop = next((j for j, c in enumerate(line) if isinstance(c, Tag) and c.name == "br"), len(line))
        line = line[:stop]
        lead = next((c for c in line if not (isinstance(c, NavigableString) and not c.strip())), None)
        if not (isinstance(lead, Tag) and lead.name in ("strong", "b", "em", "i")):
            continue
        if _has_excluded_tag(lead.get_text(" ", strip=True)) or \
                (len(_line_text(line)) <= 60 and _has_excluded_tag(_line_text(line))):
            for n in [children[i], *line]:
                n.extract()


def prune_tagged_entries(body: Tag, nav: bool = False) -> None:
    """Drop entries tagged with an excluded publisher ([LG]): a tagged heading with its section,
    and list items / paragraphs whose opening name carries the tag."""
    if not EXCLUDED_TAGS:
        return
    is_heading = lambda el: isinstance(el, Tag) and re.fullmatch(r"h[1-6]", el.name or "")
    blocks = body.find_all(["li", "p", "dt"])  # collected before anything is removed
    for h in body.find_all(re.compile(r"^h[1-6]$")):
        if h.parent is None or not _has_excluded_tag(h.get_text(" ", strip=True)):
            continue
        level = int(h.name[1])
        section, sib = [], h.find_next_sibling()
        while sib is not None and not ((is_heading(sib) and int(sib.name[1]) <= level) or sib.name == "hr"):
            section.append(sib)
            sib = sib.find_next_sibling()
        # A tagged entry's own sub-sections (an option's abilities) go with it. Where the wiki's
        # outline is off and unrelated sections sit "under" a tagged heading (every race on
        # Alternate Racial Traits is under "Enhanced Racial Traits [LG]"), only the tagged
        # heading's own text, up to its first sub-heading, is removed.
        if h.get_text(" ", strip=True).startswith(TAGGED_HEADING_TEXT_ONLY):
            first = next((i for i, s in enumerate(section) if is_heading(s)), len(section))
            section = section[:first]
        for s in section:
            s.decompose()
        h.decompose()
    for el in blocks:
        if el.parent is None:
            continue
        # single entries only: not multi-line blocks or link lists like the home page's
        # "Alchemist ([[A]], [[B]] [LG], ...)" lines, where one tag doesn't condemn the line
        if nav and (el.find("br") or len(el.find_all("a")) >= 3):
            continue
        # the tag has to sit on the entry's name: before the first comma / colon / sentence end,
        # or inside a leading bold label ("**Divine Faith: [LG]**", "**X (Ex) (-2 EP, +1 CR) [LG]**")
        if not nav:
            _prune_tagged_lines(el)  # "**Ability** text<br>**Addendum: [SM—]** text" -> drop that line
        opening = re.match(r"^[^.:,\n]{0,100}", el.get_text(" ", strip=True)).group(0)
        first = next((c for c in el.children if not (isinstance(c, NavigableString) and not c.strip())), None)
        label = first.get_text(" ", strip=True) if isinstance(first, Tag) and first.name in ("strong", "b", "em", "i") else ""
        # a short label line like "*Addendum:* [SM—]" (tag after the label, before the first <br>)
        first_line = _line_text(list(el.children))
        label_line = first_line if label and len(first_line) <= 60 else ""
        if _has_excluded_tag(opening) or _has_excluded_tag(label) or _has_excluded_tag(label_line):
            # a paragraph that is only the label (+ its source line) continues in the following
            # unlabeled paragraphs ("**Addendum: [SM—]**" then the addendum text): drop those too
            rest = el.get_text(" ", strip=True)[len(label):] if label else ""
            for sup in el.find_all("sup"):
                rest = rest.replace(sup.get_text(" ", strip=True), "")
            if el.name == "p" and label and len(rest.strip()) < 15:
                sib = el.find_next_sibling()
                while isinstance(sib, Tag) and sib.name == "p":
                    lead = next((c for c in sib.children
                                 if not (isinstance(c, NavigableString) and not c.strip())), None)
                    if isinstance(lead, Tag) and lead.name in ("strong", "b", "em", "i"):
                        break  # next labeled entry
                    nxt = sib.find_next_sibling()
                    sib.decompose()
                    sib = nxt
            el.decompose()


def prune_excluded(body: Tag, excluded: set[str]) -> None:
    """Drop links to excluded book lines from a navigation page, with their tag/separator debris."""
    # whole blocks headed by a link to an excluded hub (e.g. a book's column on the home page)
    for h in body.find_all(["h1", "h2", "h3", "h4"]):
        a = h.find("a", href=True) if h.parent else None
        if a and internal_slug(a["href"]) in excluded:
            block = h.find_parent(lambda t: t.name == "div" and (
                "sop-col" in (t.get("class") or []) or "float" in t.get("style", ""))) or h
            block.decompose()
    for a in body.find_all("a", href=True):
        if a.parent is None or internal_slug(a["href"]) not in excluded:
            continue
        parent = a.parent
        after = a.next_sibling
        before = a.previous_sibling
        is_br = lambda el: isinstance(el, Tag) and el.name == "br"
        # did the link start its line? (only then may its trailing <br> go, or lines would merge)
        line_start = before is None or is_br(before) or (
            isinstance(before, NavigableString) and not before.strip()
            and (before.previous_sibling is None or is_br(before.previous_sibling)))
        if isinstance(after, NavigableString):
            # " [3PP], " / " [DRS] |" etc. that belonged to the removed link
            # (\]+: the wiki has typos like "[LG]]" whose extra bracket would be left behind)
            cleaned = re.sub(r"^\s*(\[[^\]]*\]+\s*)*([,|·]\s*)?", "", str(after), count=1)
            after.replace_with(" " + cleaned if cleaned and not line_start else cleaned)
            after = a.next_sibling
        if line_start and is_br(after):
            after.decompose()
        a.decompose()
        if parent.name in ("li", "p", "strong") and not parent.find("a") and \
                not parent.get_text(strip=True).strip(",|·() "):
            parent.decompose()


def drop_excluded_mentions(md: str) -> str:
    """Remove prose sentences that mention an excluded book (e.g. 'X is being added to the wiki')."""
    names = "|".join(re.escape(n) for n in sorted(EXCLUDED_SECTIONS, key=len, reverse=True))
    mention = re.compile(rf"\b({names})\b", re.I)
    out = []
    for line in md.split("\n"):
        if "[[" in line or not mention.search(line):
            out.append(line)
            continue
        sentences = re.split(r"(?<=[.!?])\s+", line)
        kept = [s for s in sentences if not mention.search(s)]
        out.append(" ".join(kept))
    return "\n".join(out)


def rebalance_home_columns(md: str) -> str:
    """Move whole '**Heading**' sections between columns of the home page's main nav grid."""
    lines = md.split("\n")
    heading = lambda l: re.fullmatch(r"\*\*([^*]+)\*\*", l.strip())
    # find the grid that contains the first section we want to move
    wanted = {name for name, _ in HOME_SECTION_MOVES}
    start = None
    for i, l in enumerate(lines):
        if l.strip().startswith('<div class="sop-columns"'):
            start = i
        h = heading(l)
        if h and h.group(1) in wanted and start is not None:
            break
    else:
        return md
    # parse the grid into columns: <div class="sop-col"> ... </div> pairs, then the grid's </div>
    cols: list[list[str]] = []
    cur: list[str] | None = None
    depth = 0  # divs nested inside the current column (e.g. tabs)
    i, end = start + 1, None
    while i < len(lines):
        l = lines[i].strip()
        if l == '<div class="sop-col">' and cur is None:
            cur = []
        elif cur is not None and l.startswith("<div") and not l.endswith("</div>"):
            depth += 1
            cur.append(lines[i])
        elif l == "</div>" and cur is not None and depth:
            depth -= 1
            cur.append(lines[i])
        elif l == "</div>" and cur is not None:
            cols.append(cur)
            cur = None
        elif l == "</div>" and cur is None:
            end = i
            break
        elif cur is not None:
            cur.append(lines[i])
        i += 1
    if end is None:
        return md

    def split_sections(col: list[str]):
        """-> (prefix lines, [(name, lines)]) where a section owns the '---' separator above it."""
        idx = [k for k, l in enumerate(col) if heading(l)]
        if not idx:
            return col, []
        prefix, sections = col[:idx[0]], []
        for n, k in enumerate(idx):
            stop = idx[n + 1] if n + 1 < len(idx) else len(col)
            sections.append([heading(col[k]).group(1), col[k:stop]])
        # hand trailing separators ('---' / blanks) of each section to the next one
        for n in range(len(sections) - 1):
            body = sections[n][1]
            sep = []
            while body and body[-1].strip() in ("", "---"):
                sep.insert(0, body.pop())
            sections[n + 1][1] = sep + sections[n + 1][1]
        return prefix, sections

    parsed = [split_sections(c) for c in cols]
    for name, into in HOME_SECTION_MERGES:
        src = next(((secs, s) for _, secs in parsed for s in secs if s[0] == name), None)
        dst = next((s for _, secs in parsed for s in secs if s[0] == into), None)
        if not (src and dst):
            continue
        src[0].remove(src[1])
        links = [l for l in src[1][1] if l.strip() not in ("---",) and not heading(l)]
        while links and not links[0].strip():
            links.pop(0)
        while dst[1] and not dst[1][-1].strip():
            dst[1].pop()
        dst[1].extend(["", *links])
    for name, target in HOME_SECTION_MOVES:
        if target - 1 >= len(parsed):
            continue
        for prefix, sections in parsed:
            hit = next((s for s in sections if s[0] == name), None)
            if hit:
                sections.remove(hit)
                body = [l for l in hit[1]]
                while body and body[0].strip() in ("", "---"):
                    body.pop(0)
                parsed[target - 1][1].append([name, ["", "---", "", *body]])
                break

    # sample-character sections live on their own page now; link it from Creatures
    for _, sections in parsed:
        sections[:] = [s for s in sections if s[0] not in SAMPLE_SECTIONS]
        for name, body in sections:
            if name in HOME_SECTION_APPEND:
                while body and not body[-1].strip():
                    body.pop()
