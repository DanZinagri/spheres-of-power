# Citation tags: the wiki's source/publisher markers ("[DRS]", "[Apoc]", "[3PP]", "[Wiki]", "[CS]",
# "[Alienist HB]", "[SA:MD]", "[TS:WAT]", ...). Rules tags ([utility], [Tension], [Policy], [Dual
# Sphere], racial-feat races, Mythic Spheres 3's [HR] "highly recommended" rules) are not citations.
CITATION_CODES = (
    r"DRS|Apoc|APOC|3PP|3pp|Wiki|CS|OG|NS|Core|TS|TS:WAT|LotS|LotS addition|DbH|DBH|CoP|EO2|EO3|MCS"
    r"|BaP|SUE|BTH|CrimDan|SoG|Warden|AoP2|HMH|HMH Variant|Origin|S&P|USOP|WtD|WM|CotS|IHB2|PGtS|PGtSB"
    r"|LSP|FotC|WoP|SAA|H&B|DS:TP|VoS|UC|CC2|SA:[\w&()]+|SB:[\w&()]+|Apoc: [^\]/,]+"
    r"|Woodfaring Adventures|Spheres of Guile|Jester's Handbook|[\w.'’ ]+ HB(?: addendum)?"
    r"|Errata'd (?:in|by) [^\]/,]+"
)
CITATION_TAG_RE = re.compile(
    r"[ \t]*(?:(?<!\[)\[(?:" + CITATION_CODES + r")(?:\s*[,/]\s*(?:" + CITATION_CODES + r"))*\](?![\[(\]:])"
    # ...and the few the wiki linked to the product: "[[DRS](https://...)]", "[[SUE]]"
    r"|\[\[(?:" + CITATION_CODES + r")\](?:\([^)\s]*\))?\])")


def strip_citation_tags() -> tuple[int, int]:
    """Drop citation tags everywhere (the site no longer explains or uses them), and point links at
    the heading ids that changed with them ("#camp-of-operations-drs" -> "#camp-of-operations").
    Returns (tags removed, links rewritten)."""
    files = sorted(CONTENT.rglob("*.md"))
    moved: dict[str, dict[str, str]] = {}  # page key -> {old heading id: new id}
    key = lambda name: name.strip().lower().replace(" ", "-")
    removed = 0
    texts: dict[Path, str] = {}
    for f in files:
        text = f.read_text(encoding="utf-8")
        new, n = CITATION_TAG_RE.subn("", text)
        if n:
            removed += n
            old_slug, new_slug, ids = _slugger(), _slugger(), {}
            for a, b in zip(text.split("\n"), new.split("\n")):
                if (m := re.match(r"#{1,6} (.+)$", a)):
                    o, nw = old_slug(m.group(1)), new_slug(re.match(r"#{1,6} (.+)$", b).group(1))
                    if o != nw:
                        ids[o] = nw
            if ids:
                moved[key(f.stem)] = ids
        texts[f] = new
    relinked = 0

    def fix(m: re.Match, here: str) -> str:
        nonlocal relinked
        target, frag = m.group(1), m.group(2)
        ids = moved.get(key(target.split("/")[-1]) if target else here, {})
        if frag in ids:
            relinked += 1
            return f"[[{target}#{ids[frag]}"
        return m.group(0)
    for f, text in texts.items():
        new = re.sub(r"\[\[([^\]|#\n]*)#([^\]|\\n]+)", lambda m: fix(m, key(f.stem)), text)
        if new != f.read_text(encoding="utf-8"):
            f.write_text(new, encoding="utf-8")
    return removed, relinked


def tag_search_types() -> dict[str, int]:
    """`searchtype` frontmatter for the search page's Type filter, from what the site knows rather
    than page names: Archetypes and Class Options from the home Classes tables' columns (plus
    CLASS_OPTION_PAGES), Spheres + Talents for every home-page sphere and the talent pages in its
    folder. A page can have several ("Spheres, Talents")."""
    home = (CONTENT / "index.md").read_text(encoding="utf-8")
    types: dict[str, set[str]] = {}
    add = lambda name, t: types.setdefault(name.strip(), set()).add(t)
    at = home.find("## Classes")
    for line in home[at:].split("\n") if at >= 0 else []:
        cells = re.split(r"(?<!\\)\|", line)
        if line.startswith("| **") and len(cells) > 3:
            for t in re.findall(r"\[\[([^\]|\\#]+)", cells[2]):
                add(t, "Archetypes")
        if line.startswith("| **") and len(cells) > 4:
            for t in re.findall(r"\[\[([^\]|\\#]+)", cells[3]):
                add(t, "Class Options")
    for name in CLASS_OPTION_PAGES:
        add(name, "Class Options")
    spheres_at, spheres_end = home.find("## Spheres"), home.find("## Character Options")
    sphere_names = {m for line in home[spheres_at:spheres_end].split("\n") if line.startswith("- [[")
                    for m in re.findall(r"^- \[\[([^\]|\\#]+)", line)}
    folders: set[Path] = set()
    for f in CONTENT.rglob("*.md"):
        if f.stem in sphere_names and ARCHIVE not in f.relative_to(CONTENT).parts:
            add(f.stem, "Spheres")
            add(f.stem, "Talents")
            folders.add(f.parent)
    counts: dict[str, int] = {}
    for f in CONTENT.rglob("*.md"):
        rel = f.relative_to(CONTENT)
        if ARCHIVE in rel.parts:
            continue
        mine = set(types.get(f.stem, set()))
        if f.parent in folders and re.search(r"Talents$", f.stem):
            mine.add("Talents")  # e.g. Tinker Talents, Tinker Legendary Talents
        if any(rel.as_posix().startswith(d + "/") for d in CLASS_OPTION_FOLDERS):
            mine.add("Class Options")
        if not mine:
            continue
        text = f.read_text(encoding="utf-8")
        if not text.startswith("---\n"):
            continue
        head, rest = text[4:].split("\n---", 1)
        head = re.sub(r"^searchtype:[^\n]*\n?", "", head, flags=re.M).rstrip("\n")
        f.write_text("---\n" + head + "\nsearchtype: " + ", ".join(sorted(mine)) + "\n---" + rest, encoding="utf-8")
        for t in mine:
            counts[t] = counts.get(t, 0) + 1
    return counts


def normalize_heading_levels() -> int:
    """Pass over the written pages so the same kind of page uses the same heading sizes:
    - a first heading that just repeats the page title (Quartz shows the title) goes;
    - archetype pages: the top heading level (class features) becomes ##;
    - feat and drawback pages: the entry level (the most common one) becomes ####.
    Whole pages are shifted, so each page keeps its own hierarchy. Returns pages changed."""
    norm = lambda s: re.sub(r"[^a-z0-9]+", " ", re.sub(r"\[\[(?:[^\]|]*\|)?([^\]]*)\]\]", r"\1", s).lower()).strip()
    changed = 0
    for f in CONTENT.rglob("*.md"):
        if ARCHIVE in f.relative_to(CONTENT).parts or f.name == "index.md":
            continue
        text = f.read_text(encoding="utf-8")
        if GENERATED_MARK not in text:
            continue
        head, body = text.split(GENERATED_MARK, 1)
        lines = body.split("\n")
        title = re.search(r'^title: "?(.*?)"?$', head, re.M)
        first = next((i for i, l in enumerate(lines) if l.strip() and not l.startswith("*Source:")), None)
        if title and first is not None and (m := re.match(r"#{1,6} (.+)$", lines[first])) \
                and norm(m.group(1)) == norm(title.group(1)):
            del lines[first]
        # archetypes written as "**Feature (Ex):** text" paragraphs get feature headings like the rest
        if "Archetype" in f.stem and f.stem != "Archetype Rules" \
                and sum(1 for l in lines if re.match(r"#{1,6} ", l)) < 2:
            lines = feature_headings(lines)
        # each tab is its own block (tabs from different books nest their headings differently)
        cuts = [0] + [i for i, l in enumerate(lines) if l.strip().startswith('<div class="sop-tab"')] + [len(lines)]
        for a, b in zip(cuts, cuts[1:]):
            levels = [len(m.group(1)) for l in lines[a:b] if (m := re.match(r"(#{1,6}) ", l))]
            delta = 0
            if levels and "Archetype" in f.stem:
                delta = 2 - min(levels)
            elif levels and re.search(r"(Feats|Drawbacks)$", f.stem):
                delta = 4 - Counter(levels).most_common(1)[0][0]
                delta = max(delta, 1 - min(levels))  # never above h1
            if delta:
                lines[a:b] = [re.sub(r"^(#{1,6})(?= )", lambda m: "#" * min(6, max(1, len(m.group(1)) + delta)), l)
                              for l in lines[a:b]]
        for name, level in HEADING_LEVEL_FIXES.get(f.stem, {}).items():
            lines = [f"{'#' * level} {name}" if re.fullmatch(rf"#{{1,6}} {re.escape(name)}", l) else l for l in lines]
        new = head + GENERATED_MARK + "\n".join(lines)
        if new != text:
            f.write_text(new, encoding="utf-8")
            changed += 1
    return changed


