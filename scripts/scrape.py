# --------------------------------------------------------------------------- fetch

def sitemap() -> dict[str, str]:
    xml = session.get(f"{SITE}/sitemap.xml", timeout=60).text
    pages = {}
    for m in re.finditer(r"<url><loc>([^<]+)</loc>(?:<lastmod>([^<]+)</lastmod>)?", xml):
        slug = m.group(1).replace(SITE, "").strip("/") or "start"
        if slug in SKIP_EXACT or slug.startswith(SKIP_PREFIXES) or slug.endswith(":_template"):
            continue
        pages[slug] = m.group(2) or ""
    return pages


def cache_path(slug: str) -> Path:
    return RAW / (slug.replace(":", "__") + ".html")


def fetch_one(slug: str) -> tuple[str, str]:
    for attempt in range(5):
        try:
            r = session.get(f"{SITE}/{slug}", timeout=60)
            if r.status_code == 200:
                cache_path(slug).write_text(r.text, encoding="utf-8")
                return slug, "ok"
            if r.status_code == 404:
                return slug, "404"
        except requests.RequestException:
            pass
        time.sleep(2 ** attempt)
    return slug, "failed"


def fetch(workers: int = 4) -> None:
    RAW.mkdir(parents=True, exist_ok=True)
    pages = sitemap()
    manifest_file = CACHE / "manifest.json"
    manifest = json.loads(manifest_file.read_text()) if manifest_file.exists() else {}

    todo = [s for s, mod in pages.items()
            if not cache_path(s).exists() or manifest.get(s) != mod]
    print(f"{len(pages)} pages in sitemap, {len(todo)} to download")

    done = 0
    failed = []
    with cf.ThreadPoolExecutor(workers) as pool:
        for slug, status in pool.map(fetch_one, todo):
            done += 1
            if status == "ok":
                manifest[slug] = pages[slug]
            else:
                failed.append((slug, status))
            if done % 100 == 0:
                print(f"  {done}/{len(todo)}")
                manifest_file.write_text(json.dumps(manifest, indent=0))
    manifest_file.write_text(json.dumps(manifest, indent=0))
    (CACHE / "pages.json").write_text(json.dumps(sorted(pages)))
    if failed:
        print("Failed:", failed)


